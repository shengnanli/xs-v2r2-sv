  endtask

  // 存储基线：把全部 4 个 set × 2 路写一遍，再整体读一遍。
  // ★为什么必须有这一步★：内层 SRAMTemplate 的 rdataReg 与厂商宏里的存储阵列都**不复位**
  //   （golden SRAMTemplate_129 只有 respReg 带异步复位）。golden 与 _xs 是两个独立实例，
  //   `+vcs+initreg+random` 给它们灌的是**互不相同**的随机上电值，于是「从没写过的地址」
  //   两侧读出来本来就不同 —— 那不是 RTL 的差异，任何正确的实现都消不掉。实测：不做这一步时
  //   seed 7/42 从 cycle 17 一直错到 cycle 4123（正好是走 1 把最后一路写到为止），而
  //   `+vcs+initreg+0` 全绿。写完之后再比，才是在比逻辑。
  task automatic initmem_v1();
    idle_v1();
    @(negedge clk);
    for (int s = 0; s < 4; s++) begin
      for (int x = 0; x < 2; x++) v1_ent[x] <= rnd_ent_v1();
      v1_wvalid <= 1; v1_wset <= 2'(s); v1_waymask <= '1; v1_rvalid <= 0;
      @(negedge clk);
    end
    v1_wvalid <= 0;
    for (int s = 0; s < 4; s++) begin
      v1_rvalid <= 1; v1_rset <= 2'(s);
      @(negedge clk);
    end
    // 同样把 MBIST 侧的 rdataReg 读一遍（bore_rdata 就是这个寄存器）
    for (int i = 0; i < 1; i++) begin
      v1_back[i] <= 1; v1_bre[i] <= 1; v1_bwe[i] <= 0; v1_baddr_rd[i] <= '0;
    end
    @(negedge clk);
    @(negedge clk);
    idle_v1();
    @(negedge clk);
  endtask

  // 定向激励：走 1 / 同拍读写 / waymask 全组合 / set 边界 / 单块 hold
  task automatic directed_v1();
    int s;
    idle_v1();
    @(negedge clk);
    // A 走 1：每路、每个 entry 输入位单独置 1，写进去再读回
    for (int w = 0; w < 2; w++)
      for (int b = 0; b < V1_EW; b++) begin
        s = (b + w) % 4;
        for (int x = 0; x < 2; x++) v1_ent[x] <= '0;
        v1_ent[w] <= (V1_EW'(1) << b);
        v1_wvalid <= 1; v1_wset <= 2'(s); v1_waymask <= 2'(1) << w;
        v1_rvalid <= 0;
        @(negedge clk);
        v1_wvalid <= 0; v1_rvalid <= 1; v1_rset <= 2'(s);
        @(negedge clk);
        @(negedge clk);
      end
    // B waymask 全组合 × set 边界；同时开读写同址
    for (int m = 0; m < (1 << 2); m++)
      foreach_set_v1(m);
    // C 逐块 ram_hold：只挡住其中一块的写，制造 slice 之间不一致
    for (int i = 0; i < 1; i++) begin
      for (int x = 0; x < 2; x++) v1_ent[x] <= rnd_ent_v1();
      for (int j = 0; j < 1; j++) v1_hold[j] <= (j == i);
      v1_wvalid <= 1; v1_waymask <= '1; v1_wset <= 2'(i % 4);
      v1_rvalid <= 1; v1_rset <= 2'(i % 4);
      @(negedge clk);
      @(negedge clk);
    end
    for (int j = 0; j < 1; j++) v1_hold[j] <= 0;
    // D 逐块 MBIST bore：一次只 ack 一块，地址/数据带块号，路由错即读出不同
    for (int i = 0; i < 1; i++) begin
      for (int j = 0; j < 1; j++) begin
        v1_back[j] <= (j == i); v1_bwe[j] <= (j == i); v1_bre[j] <= (j == i);
        v1_baddr[j] <= 3'(j + 1); v1_baddr_rd[j] <= 3'(j + 1);
        v1_bwdata[j] <= 131'(j + 1);
        v1_bwmask[j] <= '1; v1_bsel[j] <= '1;
      end
      @(negedge clk);
      @(negedge clk);
    end
    idle_v1();
    @(negedge clk);
  endtask

  task automatic foreach_set_v1(int m);
    int sets[$] = '{0, 1, 4/2, 4-1};
