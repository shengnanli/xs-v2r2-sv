#!/usr/bin/env python3
"""gen_rob_ut.py -- generate Rob's dual-instantiation UT testbench from golden.

Why generated: Rob has 2200 ports (1533 in / 667 out). Port declarations, the
two instantiations and the 667 per-cycle output comparisons are purely
mechanical, and hand-copying them is not merely tedious -- it is UNDETECTABLE.
A line the tb forgot to compare is a line neither side drives, and nothing ever
goes red. So all three sections come from the G1 golden port table.

The hand-written part is the part with judgement in it: the stimulus, and the
warm-up argument below.

Why the previous round's Rob UT does not count
----------------------------------------------
`7babaa3c:verif/ut/Rob/Makefile` has `GOLDEN_SRCS =` empty and calls itself an
"invariant self-check smoke UT". The "co-sim 1/7/42" in that round's ledger is
`tb_cosim.sv`, which compares two IMPLEMENTATIONS (a packed reference against
the SoA core). Rob has never had a golden-vs-impl port-level UT. This file is
that UT.

The warm-up, and why it is argued rather than observed
------------------------------------------------------
Golden Rob has 9,359 registers with NO reset (see rob_warmup_coverage.py). They
leave reset holding whatever +vcs+initreg wrote, so a comparison window opened
before they are written compares initial values and its colour depends on the
seed. This round, StdFreeList needed a 40-seed sweep to find its 3 failing
seeds; 1/7/42 were all green. "Three seeds passed" is not evidence here.

rob_warmup_coverage.py recovers the write-enable of every one of those
registers from golden, and they reduce to three events:

    robEntries_<i>_*, debug_microOp_debugReg_<i>_*   entry i is ENQUEUED
    dt_exuDebug_<i>_*                                entry i gets a STORE writeback
    debug_exuData_<i>                                entry i gets an EXU writeback

so the tb carries three 160-bit coverage vectors and REFUSES to open the
comparison window until all three are all-ones. Enqueue acceptance is computed
inside Rob (`io_enq_canAccept` is an output), so the warm-up simply drives all
six enqueue ports at full rate and never commits: the ROB fills, and filling it
writes every entry exactly once.

Usage
  python3 scripts/gen_rob_ut.py --emit verif/ut/Rob/tb.sv
  python3 scripts/gen_rob_ut.py --check          # regenerate + diff, rc=1 on drift
  python3 scripts/gen_rob_ut.py --selftest       # port table sanity, no VCS
"""
import argparse, hashlib, os, re, sys

GOLDEN = os.environ.get(
    'ROB_GOLDEN', '/home/eda/xs-env/G1-canonical/golden-rtl/Rob.sv')

# Ports the tb drives structurally rather than randomly. Everything else is
# random every cycle -- Rob must be bit-exact under arbitrary input, and
# restricting the stimulus to "sensible" traffic is how a UT ends up only
# exercising the shapes its author already believed in.
STRUCTURAL = ('clock', 'reset')


def parse(path):
    with open(path) as f:
        text = f.read()
    lines = text.split('\n')
    start = next(i for i, l in enumerate(lines) if l.startswith('module Rob('))
    end = next(i for i in range(start, len(lines)) if lines[i].strip() == ');')
    ports = []
    for l in lines[start:end + 1]:
        m = re.match(r'\s*(input|output)\s+(?:wire\s+)?'
                     r'(?:\[\s*(\d+)\s*:\s*(\d+)\s*\])?\s*(\w+)', l)
        if m:
            hi = None if m.group(2) is None else int(m.group(2))
            lo = None if m.group(3) is None else int(m.group(3))
            ports.append((m.group(1), hi, lo, m.group(4)))
    return ports, hashlib.sha256(text.encode()).hexdigest()


def rng(hi, lo):
    return '' if hi is None else '[%d:%d] ' % (hi, lo)


def width(hi, lo):
    return 1 if hi is None else hi - lo + 1


def build(ports, digest):
    ins = [p for p in ports if p[0] == 'input' and p[3] not in STRUCTURAL]
    outs = [p for p in ports if p[0] == 'output']
    L = []
    A = L.append
    A('// Rob UT -- golden `Rob` and rewritten `Rob_xs` driven from the same')
    A('// stimulus, all %d outputs compared every cycle.' % len(outs))
    A('// GENERATED by scripts/gen_rob_ut.py from golden sha256')
    A('//   %s' % digest)
    A('// Edit the generator, not this file.')
    A('`timescale 1ns/1ps')
    A('')
    A('module tb;')
    A('  localparam int NOUT = %d;' % len(outs))
    A('')
    A('  logic clock = 1\'b0;')
    A('  logic reset = 1\'b1;')
    A('  always #5 clock = ~clock;')
    A('')
    A('  int unsigned      ncycles;')
    A('  longint unsigned  checks = 0;')
    A('  int unsigned      errors = 0;')
    A('  int unsigned      cyc    = 0;')
    A('  bit               compare_open = 1\'b0;')
    A('')
    A('  // ---- warm-up coverage (derived, see file header) ------------------')
    A('  // The window stays shut until all three vectors are all-ones. A run')
    A('  // that never opens it is a STIMULUS bug and is reported as FATAL --')
    A('  // it must never look like a quiet pass.')
    A('  logic [159:0] enq_seen = \'0;')
    A('  logic [159:0] wb_seen  = \'0;')
    A('  // st_seen is gone on purpose (see header): dt_exuDebug uses')
    A('  // io_exuWriteback_18..24, a SUBSET of the exu ports -- not a')
    A('  // separate store family. Two vectors, not three.')
    A('  wire warm_done = (&enq_seen) & (&wb_seen);')
    A('')
    A('  // BEGIN GENERATED(nets)')
    for d, hi, lo, n in ins:
        A('  logic %s%s;' % (rng(hi, lo), n))
    for d, hi, lo, n in outs:
        A('  logic %sg_%s, x_%s;' % (rng(hi, lo), n, n))
    A('  // END GENERATED')
    A('')
    A('  // BEGIN GENERATED(inst)')
    for tag, pre, mod in (('dut_g', 'g_', 'Rob'), ('dut_x', 'x_', 'Rob_xs')):
        A('  %s %s (' % (mod, tag))
        rows = ['    .clock (clock)', '    .reset (reset)']
        rows += ['    .%s (%s)' % (n, n) for _, _, _, n in ins]
        rows += ['    .%s (%s%s)' % (n, pre, n) for _, _, _, n in outs]
        A(',\n'.join(rows))
        A('  );')
        A('')
    A('  // END GENERATED')
    A('')
    A('  // ---- stimulus -----------------------------------------------------')
    A('  // ★Every initialised declaration inside a procedural block is')
    A('  // `automatic`★. A static one initialises ONCE at time 0: this round')
    A('  // that made a TLBFA run fire 6049 fence events that were all the same')
    A('  // kind (sfence.vma and hfence.vvma never issued, three seeds green),')
    A('  // and made a DecodeUnitComp run use one constant vd all the way.')
    A('  task automatic drive_random();')
    for d, hi, lo, n in ins:
        w = width(hi, lo)
        if w <= 32:
            A('    %s <= %d\'($urandom());' % (n, w))
        else:
            nw = (w + 31) // 32
            A('    %s <= %d\'({%s});' % (n, w, ', '.join(['$urandom()'] * nw)))
    A('  endtask')
    A('')
    A('  // Warm-up: six enqueue ports at full rate, never redirect. Rob decides')
    A('  // acceptance itself (io_enq_canAccept is an OUTPUT), so filling the ROB')
    A('  // is exactly what writes all 160 entries once. Writebacks sweep robIdx')
    A('  // so the exu/store debug arrays get written too.')
    A('  int unsigned wb_sweep = 0;')
    A('  task automatic drive_warmup();')
    A('    drive_random();')
    for p in range(6):
        A('    io_enq_req_%d_valid         <= 1\'b1;' % p)
        A('    io_enq_req_%d_bits_firstUop <= 1\'b1;' % p)
    A('    io_redirect_valid <= 1\'b0;')
    # Every flush/exception source held low, DERIVED from the port table
    # rather than hand-listed. Found by running the harness: driving all 25
    # writeback ports with random redirect bits flushes the ROB into walk, so
    # enqueue is refused and enq_seen stalls at 0x3f (the first six entries) --
    # the warm-up could never complete and the tb correctly went FATAL instead
    # of quietly reporting checks=0 as a pass.
    # golden Rob.sv:16447 states the acceptance gate exactly:
    #   io_enq_canAccept_0 = allowEnqueue & ~hasBlockBackward & _rab_io_canEnq
    #                        & _vtypeBuffer_io_canEnq & ~io_fromVecExcpMod_busy
    # Two of those five are INPUTS the first draft randomised, which is why
    # enq_seen stalled at 0x3f: one random blockBackward on the very first
    # enqueue latches hasBlockBackward, and a random io_fromVecExcpMod_busy
    # closes the gate outright. Read the gate, then quiet exactly its terms --
    # do not guess which signals "look like" they block enqueue.
    QUIET = [n for _, _, _, n in ins if
             n.endswith('_redirect_valid') or n.endswith('_flushPipe')
             or n.startswith('io_writebackNeedFlush_')
             or re.search(r'_exceptionVec_\d+$', n)
             or n.endswith('_bits_blockBackward')
             or n.endswith('_bits_waitForward')
             or n.endswith('_bits_hasException')
             or n.endswith('_bits_isXSTrap')
             or n == 'io_fromVecExcpMod_busy']
    for n in QUIET:
        A('    %-42s <= 1\'b0;' % n)
    A('    // Sweep every exu writeback port across every robIdx. A random')
    A('    // 8-bit robIdx would reach all 160 of 256 values only by')
    A('    // coupon-collector luck, and "it passed on three seeds" is exactly')
    A('    // the evidence this warm-up exists to stop relying on.')
    for p in range(25):
        A('    io_exuWriteback_%d_valid             <= 1\'b1;' % p)
        A('    io_exuWriteback_%d_bits_robIdx_value <= 8\'(wb_sweep);' % p)
    A('    wb_sweep <= (wb_sweep + 1) % 160;')
    A('  endtask')
    A('')
    A('  initial begin')
    A('    if (!$value$plusargs("ncycles=%d", ncycles)) ncycles = 200000;')
    A('    repeat (4) @(posedge clock);')
    A('    reset <= 1\'b0;')
    A('  end')
    A('')
    A('  // ---- coverage sampling: GOLDEN side only --------------------------')
    A('  // Reading the rewrite would let the rewrite\'s own opinion of what it')
    A('  // has covered decide when it starts being checked.')
    A('  // BEGIN GENERATED(coverage)')
    A('  always @(posedge clock) if (!reset) begin')
    for p in range(6):
        src = 'dut_g.enqPtrVec_0_value' if p == 0 else \
              'dut_g.allocatePtrVec_%d_value' % p
        A('    if (dut_g.canEnqueue_%d) enq_seen[%s] <= 1\'b1;' % (p, src))
    A('    // wb: these are inputs the TB drives, so no hierarchy needed.')
    for p in range(25):
        A('    if (io_exuWriteback_%d_valid)'
          ' wb_seen[io_exuWriteback_%d_bits_robIdx_value] <= 1\'b1;' % (p, p))
    A('  end')
    A('  // END GENERATED')
    A('')
    A('  // ---- compare -------------------------------------------------------')
    A('  always @(posedge clock) if (!reset) begin')
    A('    automatic int unsigned m = 0;')
    A('    cyc <= cyc + 1;')
    A('    if (!compare_open && warm_done) compare_open <= 1\'b1;')
    A('    if (compare_open) begin')
    A('      // BEGIN GENERATED(compare)')
    for d, hi, lo, n in outs:
        A('      if (g_%s !== x_%s) begin' % (n, n))
        A('        m++;')
        A('        if (errors + m <= 20) $display("[%%0t] MISMATCH %s g=%%h x=%%h",'
          ' $time, g_%s, x_%s);' % (n, n, n))
        A('      end')
    A('      // END GENERATED')
    A('      checks <= checks + NOUT;')
    A('      errors <= errors + m;')
    A('    end')
    A('    if (cyc >= ncycles) begin')
    A('      if (!compare_open) begin')
    A('        $display("FATAL: warm-up never completed after %0d cycles", cyc);')
    A('        $display("  enq_seen=%h", enq_seen);')
    A('        $display("  wb_seen =%h", wb_seen);')
    A('        $display("checks=0 errors=1  (warm-up failure counts as an error)");')
    A('        $finish;')
    A('      end')
    A('      $display("checks=%0d errors=%0d", checks, errors);')
    A('      $finish;')
    A('    end')
    A('  end')
    A('')
    A('  always @(posedge clock) if (!reset) begin')
    A('    if (!compare_open) drive_warmup(); else drive_random();')
    A('  end')
    A('endmodule')
    return '\n'.join(L) + '\n'


def selftest(ports):
    ins = [p for p in ports if p[0] == 'input']
    outs = [p for p in ports if p[0] == 'output']
    rows = [
        ('port_total', len(ports) == 2200, '2200 ports parsed (measured)'),
        ('split', len(ins) == 1533 and len(outs) == 667,
         '1533 in / 667 out'),
        ('no_dup', len({p[3] for p in ports}) == len(ports),
         'no duplicate port name'),
        ('enq_present', any(p[3] == 'io_enq_req_0_bits_firstUop' for p in ports),
         'the warm-up handle exists'),
        ('canaccept_is_output',
         any(p[0] == 'output' and p[3] == 'io_enq_canAccept' for p in ports),
         'io_enq_canAccept is an OUTPUT -- Rob decides acceptance, tb cannot force it'),
    ]
    ok = True
    for name, good, why in rows:
        print('%-22s %-5s %s' % (name, 'OK' if good else 'FAIL', why))
        ok &= good
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--golden', default=GOLDEN)
    ap.add_argument('--emit')
    ap.add_argument('--check')
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args()
    ports, digest = parse(a.golden)
    if a.selftest:
        return selftest(ports)
    body = build(ports, digest)
    if a.check:
        with open(a.check) as f:
            cur = f.read()
        same = cur == body
        print('gen_rob_ut --check: %s' % ('OK' if same else 'DRIFT'))
        return 0 if same else 1
    if a.emit:
        os.makedirs(os.path.dirname(os.path.abspath(a.emit)), exist_ok=True)
        with open(a.emit, 'w') as f:
            f.write(body)
        print('wrote %s (%d lines)' % (a.emit, body.count('\n')), file=sys.stderr)
        return 0
    sys.stdout.write(body)
    return 0


if __name__ == '__main__':
    sys.exit(main())
