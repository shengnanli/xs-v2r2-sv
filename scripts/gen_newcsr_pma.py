#!/usr/bin/env python3
"""Generate the PMA CSR family wrappers for NewCSR.

The golden PMA CSR family (34 modules) is highly regular:

  * Pmacfg{0,2}Module   : pure-comb 64-bit read slice of the packed 128-bit PMA
                          config bus  ->  xs_pmacfg_slice #(.HI())
  * Pmaaddr{0..15}Module: pure-comb pass-through of addrRData_N
                          ->  xs_pmaaddr (binds golden per-index port name)
  * Pma{0..15}cfgModule : one config-entry register (R/W/X/A/ATOMIC/C/L); the
                          ONLY per-index difference is the async-reset default
                          value  ->  xs_pmacfg_entry #(.RESET_VAL())

Every reset default below is transcribed from the corresponding golden module's
`if (reset)` block. Field/bit layout: {L[7],C[6],ATOMIC[5],A[4:3],X[2],W[1],R[0]}.

Outputs: rtl/backend/newcsr_pma_wrappers.sv.
FM-verified per module in signoff-strict mode via the Pma0cfgModule AUX UT.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "rtl", "backend", "newcsr_pma_wrappers.sv")

# Per-entry async-reset default {L,C,ATOMIC,A[1:0],X,W,R}, from golden.
PMACFG_RESET = {
    0: 0x00, 1: 0x00, 2: 0x00,
    3: 0x0B,          # R,W,A=1
    4: 0x0F,          # R,W,X,A=1
    5: 0x0B, 6: 0x0B, 7: 0x0B,
    8: 0x0F,          # R,W,X,A=1
    9: 0x0B, 10: 0x0B, 11: 0x0B,
    12: 0x08,         # A=1
    13: 0x0B,
    14: 0x6F,         # R,W,X,A=1,ATOMIC,C
    15: 0x18,         # A=3
}

HEADER = """// NewCSR PMA family AUX wrappers (34 golden modules).
// GENERATED by scripts/gen_newcsr_pma.py. Thin wrappers over the readable
// primitives in rtl/backend/newcsr_pma.sv, binding golden per-instance ports.
// FM-verified per module in signoff-strict mode (no blackbox / no dont_verify).

"""

PMACFG_SLICE = """// ===== Pmacfg{{0,2}}Module: 64-bit read slice of packed 128-bit PMA cfg bus =====
module Pmacfg{n}Module(
  output [63:0]  rdata,
  input  [127:0] cfgRData
);
  xs_pmacfg_slice #(.HI(1'b{hi})) u_core (.rdata(rdata), .cfgRData(cfgRData));
endmodule

"""

PMAADDR = """module Pmaaddr{n}Module(
  output [63:0] rdata,
  input  [63:0] addrRData_{n}
);
  xs_pmaaddr u_core (.rdata(rdata), .addr_rdata(addrRData_{n}));
endmodule

"""

PMACFG_ENTRY = """module Pma{n}cfgModule(
  input         clock,
  input         reset,
  input         w_wen,
  input  [63:0] w_wdata,
  output [7:0]  rdata,
  output        regOut_R,
  output        regOut_W,
  output        regOut_X,
  output [1:0]  regOut_A,
  output        regOut_ATOMIC,
  output        regOut_C,
  output        regOut_L
);
  xs_pmacfg_entry #(.RESET_VAL(8'h{rv:02X})) u_core (
    .clock(clock), .reset(reset), .w_wen(w_wen), .w_wdata(w_wdata),
    .rdata(rdata), .regOut_R(regOut_R), .regOut_W(regOut_W), .regOut_X(regOut_X),
    .regOut_A(regOut_A), .regOut_ATOMIC(regOut_ATOMIC), .regOut_C(regOut_C),
    .regOut_L(regOut_L));
endmodule

"""


def main():
    parts = [HEADER]
    parts.append(PMACFG_SLICE.format(n=0, hi=0))
    parts.append(PMACFG_SLICE.format(n=2, hi=1))
    parts.append("// ===== Pmaaddr{0..15}Module: pass-through per-entry addr read =====\n")
    for i in range(16):
        parts.append(PMAADDR.format(n=i))
    parts.append("// ===== Pma{0..15}cfgModule: config-entry register (per-index reset) =====\n")
    for i in range(16):
        parts.append(PMACFG_ENTRY.format(n=i, rv=PMACFG_RESET[i]))
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
