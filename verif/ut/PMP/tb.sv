  function automatic logic [7:0] rand_cfg();
    logic [7:0] c = 8'($urandom);
    c[7] = ($urandom_range(0, 63) == 0);          // l
    return c;
  endfunction

  task automatic drive_inputs();
    int k;
    io_distribute_csr_w_valid = ($urandom_range(0, 9) < 6);
    k = $urandom_range(0, 99);
    if (k < 85) begin
      case ($urandom_range(0, 3))
        0: io_distribute_csr_w_bits_addr = 12'h3A0 + 12'(2 * $urandom_range(0, 3));
        1: io_distribute_csr_w_bits_addr = 12'h3B0 + 12'($urandom_range(0, 31));
        2: io_distribute_csr_w_bits_addr = 12'h7C0 + 12'(2 * $urandom_range(0, 3));
        default: io_distribute_csr_w_bits_addr = 12'h7C8 + 12'($urandom_range(0, 31));
      endcase
    end else if (k < 92) begin
      io_distribute_csr_w_bits_addr = ($urandom_range(0, 1) ? 12'h3A1 : 12'h7C1) + 12'(2 * $urandom_range(0, 3));
    end else begin
      io_distribute_csr_w_bits_addr = 12'($urandom);
    end
    if (io_distribute_csr_w_bits_addr[11:4] == 8'h3A || io_distribute_csr_w_bits_addr[11:3] == 9'h0F8)
      io_distribute_csr_w_bits_data = {rand_cfg(), rand_cfg(), rand_cfg(), rand_cfg(),
                                       rand_cfg(), rand_cfg(), rand_cfg(), rand_cfg()};
    else
      io_distribute_csr_w_bits_data = {32'($urandom), 32'($urandom)}
                                      | (($urandom_range(0, 1)) ? ((64'd1 << $urandom_range(0, 40)) - 1) : 64'd0);
  endtask

  longint n_cfgw, n_addrw, n_cfg_locked, n_addr_locked, n_tor_lock, n_napot;
  bit     cov_on = 0;
  // 覆盖：从重写核内部看（比较通过时两侧逐位相等）；generate 下标必须是常量，所以逐项一个 always
  for (genvar t = 0; t < 2; t++) begin : g_cov_t
    for (genvar k = 0; k < 4; k++) begin : g_cov_k
      always @(negedge clk) if (cov_on && x_dut.u_core.cfg_wen[t][k]) n_cfgw++;
    end
    for (genvar i = 0; i < 32; i++) begin : g_cov_i
      always @(negedge clk) if (cov_on) begin
        if (x_dut.u_core.addr_wen[t][i]) n_addrw++;
        if (x_dut.u_core.addr_wen[t][i] && x_dut.u_core.mapping[t].g_entry[i].addr_locked) n_addr_locked++;
        if (x_dut.u_core.addr_wen[t][i] && x_dut.u_core.mapping[t].g_entry[i].next_locks_me) n_tor_lock++;
        if (x_dut.u_core.cfg_wen[t][i / 8] && x_dut.u_core.cfg[t][i].l) n_cfg_locked++;
        if (x_dut.u_core.mapping[t].g_entry[i].cfg_napot_write) n_napot++;
      end
    end
  end
  initial begin
    if (!$value$plusargs("ncycles=%d", NCYCLES)) NCYCLES = 200000;
    reset = 1;
    drive_inputs();
    repeat (10) @(negedge clk);
    reset = 0;
    cov_on = 1;
    for (longint c = 0; c < NCYCLES; c++) begin
      if (c > 1000 && $urandom_range(0, 2999) == 0) begin
        reset = 1;
        repeat (3) begin drive_inputs(); @(negedge clk); end
        reset = 0;
      end
      drive_inputs();
      #1;
      checks++;
      if (g_all !== x_all) begin
        errors++;
        if (errors <= 20) $display("[%0t] MISMATCH diff=%h", $time, g_all ^ x_all);
      end
      @(negedge clk);
    end
    $display("=== COVERAGE (PMP) === checks=%0d cfg_write=%0d addr_write=%0d cfg_locked=%0d addr_locked=%0d tor_lock=%0d napot_remask=%0d",
             checks, n_cfgw, n_addrw, n_cfg_locked, n_addr_locked, n_tor_lock, n_napot);
    if (n_cfgw == 0 || n_addrw == 0 || n_cfg_locked == 0 || n_addr_locked == 0 || n_tor_lock == 0 || n_napot == 0) begin
      $display("COVERAGE INSUFFICIENT");
      errors++;
    end
    if (errors == 0) $display("TEST PASSED (checks=%0d errors=0)", checks);
    else             $display("TEST FAILED errors=%0d (checks=%0d)", errors, checks);
    $finish;
  end
