// PMP UT —— golden PMP 对重写 PMP_xs 双例化，同激励逐拍比对全部 480 根输出（6432 位，拼成一个向量比）。
//
// 激励要点（判别力来自哪里）：
//   · 写地址 85% 取 72 个有效 CSR 地址（pmpcfg0/2/4/6、pmpaddr0..31、pmacfg0/2/4/6、pmaaddr0..31），
//     其余是奇数号 cfg / 越界 / 随机地址（必须不写任何表）；写有效 60%。
//   · cfg 字节：a 取 0~3（NA4 并 NAPOT 的路径）、W=1/R=0 保留组合、x/c/atomic 随机；l 置位 1/64
//     （锁住后 cfg 与 addr 都不可写，且锁住的 TOR 会锁住前一项的 addr）。
//   · addr 数据：随机 64 位，常带一串低位 1（NAPOT 区域大小各异）。
//   · 约每 3000 拍一次 3 拍复位脉冲（锁会被复位解开，复位期间不比）。
// 比较窗口：所有表寄存器都异步复位，wdata_reg 只在"上一拍有写"时被读，所以从复位释放起逐拍全比。
// 覆盖判据：cfg 写 / addr 写 / 锁住拒写（cfg 与 addr 各）/ TOR 锁前项 / NAPOT mask 重算 都必须发生过。
// =============================================================================
