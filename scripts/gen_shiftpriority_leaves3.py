#!/usr/bin/env python3
"""Generate three more readable FP-normalize priority-shifter leaves.

Same family as scripts/gen_shiftpriority_leaves2.py (already signed; that
generator and its two outputs are left untouched).  This generator is the
parameterized form of the same template: the side output is either the shift
amount itself ("lzd") or a biased exponent EXP_BIAS - shift_amount ("exp"),
with the side-output width and the bias as parameters instead of constants.

Chisel source (yunsuan): ShiftLeftPriorityWithLZDResult(srcW, priorityShiftValueW)
in vector/FloatAdderReductionF32WidenF16.scala and
ShiftLeftPriorityWithF64EXPResult(srcW, priorityShiftValueW, expW) in
vector/VectorFloatAdder.scala.  Both recurse from bit WIDTH-1 down to bit 0:
the highest set select bit k wins, data is shifted left by WIDTH-1-k, and the
i==0 arm is unconditional (all-zero select -> shift by WIDTH, data 0).

Semantics re-derived from the G1 golden files:
  ShiftLeftPriorityWithLZDResult_6 (WIDTH=24, VectorFloatDividerR64):
      io_lzd_result = 23-k (5 bit); all-zero select -> lzd 24 (5'h18)
  ShiftLeftPriorityWithLZDResult_8 (WIDTH=11, VectorFloatDividerR64):
      io_lzd_result = 10-k (4 bit); all-zero select -> lzd 11
      (golden spells it {3'h5, ~sel[0]} = 4'b1011 after constant folding)
  ShiftLeftPriorityWithF64EXPResult (WIDTH=23, FloatAdderWidenFormat):
      io_exp_result = 0x380 - (22-k) (11 bit, 0x380..0x36A);
      all-zero select -> exp 0x369 (= 0x380 - 23)
"""

import argparse
from pathlib import Path


RTL_DIR = Path(__file__).resolve().parents[1] / "rtl/backend"


def shift_priority(name: str, width: int, count_w: int, side_w: int,
                   exp_bias, role: str, side_desc: str) -> str:
    """Readable core + golden-named wrapper for one priority-shifter leaf.

    exp_bias None -> side output is the shift amount itself (LZD flavor);
    otherwise side output = exp_bias - shift_amount (rebased exponent).
    """
    hi = width - 1
    if exp_bias is None:
        side_port = "lzd_result"
        side_assign = "lzd_result    = shift_amount;"
        extra_param = ""
        fallback_side = f"{width}"
    else:
        side_port = "exp_result"
        side_assign = f"exp_result    = {side_w}'(EXP_BIAS - shift_amount);"
        extra_param = (f"  localparam int EXP_BIAS = 'h{exp_bias:X}; "
                       "// golden constant: exp = EXP_BIAS - shift amount\n")
        fallback_side = f"'h{exp_bias - width:X} (= 'h{exp_bias:X} - {width})"
    return f'''// {name}.sv — {role}
//
// io_priority_shiftValue is a per-shift-amount select vector (conceptually
// one-hot, but every bit pattern is legal): the highest set bit wins and
// io_src is shifted left by that amount.  {side_desc}
// An all-zero select vector (the classic Chisel PriorityMux unconditional
// last arm) shifts by WIDTH: io_lshift_result = 0 and the side output takes
// the fallback value {fallback_side}.
//
// Pure combinational: no registers, no submodules.  The readable core
// expresses the golden ternary chain as a leading-zero count plus a single
// barrel shift; the wrapper keeps the golden port names exactly.
// Generated by scripts/gen_shiftpriority_leaves3.py (--check for drift).

module xs_{name}_core (
  input  logic [{hi}:0] src,
  input  logic [{hi}:0] priority_select,
  output logic [{hi}:0] lshift_result,
  output logic [{side_w - 1}:0] {side_port}
);
  localparam int WIDTH   = {width};
  localparam int COUNT_W = {count_w};  // must hold 0..WIDTH (fallback count)
{extra_param}
  logic [COUNT_W-1:0] shift_amount;

  always_comb begin
    // Highest set bit wins: scanning upward, each set bit overrides the
    // previous candidate, so the last (highest-index) match survives.
    // With no bit set, the fallback count WIDTH reproduces the golden
    // unconditional last arm (zero shift result, fallback side output).
    shift_amount = COUNT_W'(WIDTH);
    for (int idx = 0; idx < WIDTH; idx++)
      if (priority_select[idx])
        shift_amount = COUNT_W'(WIDTH - 1 - idx);

    lshift_result = src << shift_amount;
    {side_assign}
  end
endmodule

module {name} (
  input  logic [{hi}:0] io_src,
  input  logic [{hi}:0] io_priority_shiftValue,
  output logic [{hi}:0] io_lshift_result,
  output logic [{side_w - 1}:0] io_{side_port}
);
  xs_{name}_core u_core (
    .src(io_src),
    .priority_select(io_priority_shiftValue),
    .lshift_result(io_lshift_result),
    .{side_port}(io_{side_port})
  );
endmodule
'''


OUTPUTS = {
    "ShiftLeftPriorityWithLZDResult_6": shift_priority(
        "ShiftLeftPriorityWithLZDResult_6", 24, 5, 5, None,
        "24-bit leading-zero-detect priority left shifter on the "
        "VectorFloatDividerR64 normalize path.",
        "io_lzd_result reports the shift amount directly (0..23)."),
    "ShiftLeftPriorityWithLZDResult_8": shift_priority(
        "ShiftLeftPriorityWithLZDResult_8", 11, 4, 4, None,
        "11-bit leading-zero-detect priority left shifter on the "
        "VectorFloatDividerR64 normalize path.",
        "io_lzd_result reports the shift amount directly (0..10)."),
    "ShiftLeftPriorityWithF64EXPResult": shift_priority(
        "ShiftLeftPriorityWithF64EXPResult", 23, 5, 11, 0x380,
        "f64 exponent-adjust priority left shifter on the "
        "FloatAdderWidenFormat normalize path.",
        "io_exp_result reports the rebased exponent 'h380 - shift_amount "
        "('h380 for the unshifted case down to 'h36A for a shift of 22)."),
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    drift = []
    for module, contents in OUTPUTS.items():
        path = RTL_DIR / f"{module}.sv"
        if args.check:
            if not path.exists() or path.read_text() != contents:
                drift.append(str(path))
        elif not path.exists() or path.read_text() != contents:
            path.write_text(contents)

    if drift:
        print("gen_shiftpriority_leaves3 --check: DRIFT: " + " ".join(drift))
        raise SystemExit(1)
    if args.check:
        print(f"gen_shiftpriority_leaves3 --check: OK ({len(OUTPUTS)} files)")


if __name__ == "__main__":
    main()
