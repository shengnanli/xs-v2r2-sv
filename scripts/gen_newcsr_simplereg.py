#!/usr/bin/env python3
"""gen_newcsr_simplereg.py — transcribe simple single-purpose NewCSR register
modules from golden into readable synthesizable SystemVerilog.

These golden modules (Sbpctl, Spfctl, Mcountinhibit, Hgeie, Vstart, Srnctl, ...)
are already plain structural RTL: an always_ff with an async-reset arm and a
w_wen write arm, plus continuous rdata packing / regOut fan-out. The ONLY
non-synthesizable content is the CIRCT `ifdef ENABLE_INITIAL_REG_` randomize-init
block (sim power-up randomization) — which UT deliberately disables via
+define+SYNTHESIS. A faithful readable rewrite is exactly: the golden module body
with that init block removed and a documenting header prepended. We verify each
result with strict Formality golden-vs-impl, so any transcription slip is caught.

Usage: gen_newcsr_simplereg.py <GOLDEN_DIR> <OUT_FILE> <Module> [<Module> ...]
Emits all requested modules into one wrappers file (unchanged module names).
"""
import re
import sys


def extract_body(golden_path):
    txt = open(golden_path).read()
    # module <Name>( ... ) ... endmodule  (first/only module in file)
    m = re.search(r'\nmodule\s+\w+\s*\(', txt)
    if not m:
        raise RuntimeError(f"no module in {golden_path}")
    start = m.start() + 1  # drop leading newline
    end = txt.index('\nendmodule', start) + len('\nendmodule')
    body = txt[start:end]
    # strip the `ifdef ENABLE_INITIAL_REG_ ... `endif // ENABLE_INITIAL_REG_ block
    body = re.sub(
        r'[ \t]*`ifdef ENABLE_INITIAL_REG_.*?`endif // ENABLE_INITIAL_REG_\n',
        '', body, flags=re.DOTALL)
    # tidy the CIRCT trailing comments on always/assign for readability
    body = body.replace('  end // always @(posedge, posedge)', '  end')
    body = body.replace('  end // always @(posedge)', '  end')
    # collapse any run of 3+ blank lines
    body = re.sub(r'\n{3,}', '\n\n', body)
    return body.rstrip() + '\n'


def main():
    golden_dir = sys.argv[1]
    out_file = sys.argv[2]
    mods = sys.argv[3:]
    parts = [
        "// NewCSR simple single-purpose register CSRs — readable transcriptions.\n"
        "//\n"
        "// Each golden module here is already plain structural RTL (async-reset\n"
        "// always_ff + w_wen write arm + rdata packing). The readable rewrite is the\n"
        "// golden body with the non-synthesizable `ifdef ENABLE_INITIAL_REG_ sim\n"
        "// randomize-init block removed. FM-verified strict golden-vs-impl SUCCEEDED,\n"
        "// no black box, no dont_verify. Generated by scripts/gen_newcsr_simplereg.py.\n"
    ]
    for mod in mods:
        parts.append("\n" + extract_body(f"{golden_dir}/{mod}.sv"))
    open(out_file, 'w').write("\n".join(parts))
    print(f"wrote {len(mods)} modules -> {out_file}")


if __name__ == '__main__':
    main()
