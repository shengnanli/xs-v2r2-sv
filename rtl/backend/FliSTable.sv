// =============================================================================
// FliSTable —— FLI.S 指令的 32 项常数表（5 位立即数 -> 16 位浮点位型）
//
// 在哪一层：后端 IntFPToVec（标量浮点 -> 向量寄存器那条通路）执行 Zfa 扩展的 fli.s rd, imm 时，
//   用 rs1 字段的 5 位编码查这张表得到常数（Scala：xiangshan/backend/fu/fpu/FliTable.scala）。
// 输出含义：单精度 FP32 的高 16 位（低 16 位恒 0，由 IntFPToVec 补）。
// 机制：纯组合查表，32 个输入全有定义（Scala 用 decoder + TruthTable，默认值 BitPat.N 永远用不到），
//   golden 被 firtool 展成按位与或式；这里还原成 Scala 那张表本身，逐项附 Scala 的注释。
// 无状态、无时钟。golden 对照：G1-canonical/golden-rtl/FliSTable.sv
// =============================================================================
module FliSTable (
  input  logic [4:0]  src,
  output logic [15:0] out
);

  // ---- 常数表：下标 = fli 立即数编码，值 = 浮点位型（与 Scala Seq 逐项同序）----
  localparam logic [15:0] FLI_TABLE [32] = '{
    16'hBF80,  //  0: -1.0
    16'h0080,  //  1: minimum positive normal
    16'h3780,  //  2: 1.0 * 2^-16
    16'h3800,  //  3: 1.0 * 2^-15
    16'h3B80,  //  4: 1.0 * 2^-8
    16'h3C00,  //  5: 1.0 * 2^-7
    16'h3D80,  //  6: 1.0 * 2^-4
    16'h3E00,  //  7: 1.0 * 2^-3
    16'h3E80,  //  8: 0.25
    16'h3EA0,  //  9: 0.3125
    16'h3EC0,  // 10: 0.375
    16'h3EE0,  // 11: 0.4375
    16'h3F00,  // 12: 0.5
    16'h3F20,  // 13: 0.625
    16'h3F40,  // 14: 0.75
    16'h3F60,  // 15: 0.875
    16'h3F80,  // 16: 1.0
    16'h3FA0,  // 17: 1.25
    16'h3FC0,  // 18: 1.5
    16'h3FE0,  // 19: 1.75
    16'h4000,  // 20: 2.0
    16'h4020,  // 21: 2.5
    16'h4040,  // 22: 3
    16'h4080,  // 23: 4
    16'h4100,  // 24: 8
    16'h4180,  // 25: 16
    16'h4300,  // 26: 2^7
    16'h4380,  // 27: 2^8
    16'h4700,  // 28: 2^15
    16'h4780,  // 29: 2^16
    16'h7F80,  // 30: +inf
    16'h7FC0   // 31: CNaN
  };

  assign out = FLI_TABLE[src];
endmodule
