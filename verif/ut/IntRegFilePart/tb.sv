  // ---- tb 影子状态（posedge 更新） ----
  logic          written [NV][NP];   // 该行被写过至少一次
  logic [DW-1:0] model   [NV][NP];   // 影子寄存器堆
  logic [7:0]    rq_addr [NV][NR];   // 影子读地址寄存器
  logic          rq_valid;           // 读地址寄存器已被 tb 驱动过至少一次
  bit            cmp_all;

  initial begin
    for (int v = 0; v < NV; v++) begin
      for (int i = 0; i < NP; i++) begin
        written[v][i] = 1'b0;
        model[v][i]   = '0;
      end
    end
    rq_valid = 1'b0;
  end

  always @(posedge clock) begin
    for (int v = 0; v < NV; v++) begin
      // 每个有效写口：把本拍所有写同一地址的口的数据按位或，作为该行的新值
      for (int w = 0; w < NW; w++) begin
        if (wwen[v][w] && waddr[v][w] != 0 && waddr[v][w] < NP) begin
          logic [DW-1:0] d;
          d = '0;
          for (int u = 0; u < NW; u++)
            if (wwen[v][u] && waddr[v][u] == waddr[v][w]) d = d | wdata[v][u];
          model[v][waddr[v][w]]   <= d;
          written[v][waddr[v][w]] <= 1'b1;
        end
      end
      for (int r = 0; r < NR; r++) rq_addr[v][r] <= raddr[v][r];
    end
    rq_valid <= 1'b1;
  end

  // ---- 计数 ----
  longint checks = 0, errors = 0, model_checks = 0;
  longint cov_collide = 0, cov_collide3 = 0, cov_wr_x0 = 0, cov_wr_oob = 0;
  longint cov_rd_x0 = 0, cov_rd_oob = 0, cov_raw_same = 0, cov_rd_written = 0;

  task automatic report_err(string what, int v, int idx, logic [DW-1:0] g, logic [DW-1:0] x, int cyc);
    errors++;
    if (errors <= 20)
      $display("[ERR] cyc=%0d v=%0d %s[%0d] gold=%h other=%h", cyc, v, what, idx, g, x);
  endtask

  task automatic check_outputs(int cyc);
    for (int v = 0; v < NV; v++) begin
      if (rq_valid) begin
        for (int r = 0; r < NR; r++) begin
          int a;
          logic known;
          a = rq_addr[v][r];
          known = (a == 0) || (a >= NP) || written[v][a];
          if (a == 0) cov_rd_x0++;
          else if (a >= NP) cov_rd_oob++;
          else if (written[v][a]) cov_rd_written++;
          if (known || cmp_all) begin
            checks++;
            if (g_rd[v][r] !== x_rd[v][r]) report_err("read", v, r, g_rd[v][r], x_rd[v][r], cyc);
          end
          if (known) begin
            logic [DW-1:0] exp;
            exp = (a == 0 || a >= NP) ? '0 : model[v][a];
            model_checks++;
            if (g_rd[v][r] !== exp) report_err("read_vs_model", v, r, g_rd[v][r], exp, cyc);
          end
        end
      end
      for (int i = 1; i < NP; i++) begin
        if (written[v][i] || cmp_all) begin
          checks++;
          if (g_dbg[v][i] !== x_dbg[v][i]) report_err("debug", v, i, g_dbg[v][i], x_dbg[v][i], cyc);
        end
        if (written[v][i]) begin
          model_checks++;
          if (g_dbg[v][i] !== model[v][i]) report_err("debug_vs_model", v, i, g_dbg[v][i], model[v][i], cyc);
        end
      end
    end
  endtask

  // ---- 激励 ----
  int unsigned hot [NV][4];          // 热点地址：制造反复读写与同址冲突
  int unsigned wen_pct;              // 本阶段写口使能概率（%）

  function automatic logic [7:0] pick_addr(int v);
    int unsigned p;
    p = $urandom_range(0, 99);
    if (p < 4)       return 8'd0;                                  // x0
    else if (p < 10) return 8'(NP + $urandom_range(0, 255 - NP));  // 越界 224..255
    else if (p < 40) return 8'(hot[v][$urandom_range(0, 3)]);      // 热点
    else             return 8'($urandom_range(1, NP - 1));
  endfunction

  task automatic drive_inputs(int cyc);
    if (cyc % 1000 == 0) begin
      for (int v = 0; v < NV; v++)
        for (int k = 0; k < 4; k++) hot[v][k] = $urandom_range(1, NP - 1);
    end
    if (cyc % 5000 == 0) begin
      case ($urandom_range(0, 2))
        0: wen_pct = 15;
        1: wen_pct = 50;
        default: wen_pct = 90;
      endcase
    end
    for (int v = 0; v < NV; v++) begin
      int n_hit_same;
      for (int w = 0; w < NW; w++) begin
        wwen[v][w]  = ($urandom_range(0, 99) < wen_pct);
        waddr[v][w] = pick_addr(v);
        wdata[v][w] = DW'($urandom);
      end
      // 同址多写：约 10% 的拍把 2~3 个写口压到同一地址（golden = 按位或）
      if ($urandom_range(0, 9) == 0) begin
        int w1, w2, w3;
        w1 = $urandom_range(0, NW - 1);
        w2 = (w1 + 1 + $urandom_range(0, NW - 2)) % NW;
        wwen[v][w1] = 1'b1;
        wwen[v][w2] = 1'b1;
        waddr[v][w2] = waddr[v][w1];
        if ($urandom_range(0, 2) == 0) begin
          w3 = (w2 + 1) % NW;
          if (w3 != w1) begin
            wwen[v][w3]  = 1'b1;
            waddr[v][w3] = waddr[v][w1];
          end
        end
      end
      for (int r = 0; r < NR; r++) begin
        // 约 20% 的读口读本拍正在写的地址（同拍写后读：下一拍应读到新值）
        if ($urandom_range(0, 4) == 0) raddr[v][r] = waddr[v][$urandom_range(0, NW - 1)];
        else                           raddr[v][r] = pick_addr(v);
      end
      // 覆盖计数
      for (int w = 0; w < NW; w++) begin
        if (wwen[v][w] && waddr[v][w] == 0) cov_wr_x0++;
        if (wwen[v][w] && waddr[v][w] >= NP) cov_wr_oob++;
      end
      begin
        int maxsame;
        maxsame = 0;
        for (int w = 0; w < NW; w++) begin
          int c;
          c = 0;
          if (wwen[v][w] && waddr[v][w] != 0 && waddr[v][w] < NP)
            for (int u = 0; u < NW; u++)
              if (wwen[v][u] && waddr[v][u] == waddr[v][w]) c++;
          if (c > maxsame) maxsame = c;
        end
        if (maxsame >= 2) cov_collide++;
        if (maxsame >= 3) cov_collide3++;
      end
      for (int r = 0; r < NR; r++)
        for (int w = 0; w < NW; w++)
          if (wwen[v][w] && waddr[v][w] == raddr[v][r] && raddr[v][r] != 0 && raddr[v][r] < NP) begin
            cov_raw_same++;
            break;
          end
    end
  endtask

  int ncycles;
  initial begin
    if (!$value$plusargs("ncycles=%d", ncycles)) ncycles = 200000;
    cmp_all = $test$plusargs("cmp_all");
    for (int v = 0; v < NV; v++) begin
      for (int r = 0; r < NR; r++) raddr[v][r] = '0;
      for (int w = 0; w < NW; w++) begin
        wwen[v][w] = 1'b0; waddr[v][w] = '0; wdata[v][w] = '0;
      end
    end
    wen_pct = 50;
    drive_inputs(0);
    repeat (3) @(negedge clock);
    reset = 1'b0;
    for (int cyc = 1; cyc <= ncycles; cyc++) begin
      // 先驱动下一拍激励、再比对：golden 的输出只取决于寄存器，此刻输入已换成新值，
      // 任何"输出偷看了当拍输入"（如读口不打拍、组合旁路）都会在这里露出来。
      @(negedge clock);
      drive_inputs(cyc);
      #1;
      check_outputs(cyc);
    end
    $display("coverage: collide2=%0d collide3=%0d wr_x0=%0d wr_oob=%0d rd_x0=%0d rd_oob=%0d rd_written=%0d raw_same_cycle=%0d cmp_all=%0d",
             cov_collide, cov_collide3, cov_wr_x0, cov_wr_oob, cov_rd_x0, cov_rd_oob, cov_rd_written, cov_raw_same, cmp_all);
    $display("model_checks=%0d", model_checks);
    $display("checks=%0d errors=%0d", checks, errors);
    if (errors == 0 && checks > 0) $display("TEST PASSED");
    else                           $display("TEST FAILED");
    $finish;
  end
