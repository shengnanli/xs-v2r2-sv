  // 随机一拍激励（含 bore 与 per-block ram_hold）
  task automatic rnd_v1();
    v1_rvalid <= ($urandom_range(0,3) != 0);
    v1_wvalid <= ($urandom_range(0,2) == 0);
    v1_rset   <= 2'($urandom);
    v1_wset   <= 2'($urandom);
