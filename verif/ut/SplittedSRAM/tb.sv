  task automatic chk_v2();
    if (v2_g_tag !== v2_i_tag) begin
      rep("SplittedSRAM_2.tag");
      if (errors <= 10) $display("        g_tag=%h i_tag=%h rvalid=%b rset=%h", v2_g_tag, v2_i_tag, v2_rvalid, v2_rset);
    end
    if (v2_g_asid !== v2_i_asid) rep("SplittedSRAM_2.asid");
    if (v2_g_vmid !== v2_i_vmid) rep("SplittedSRAM_2.vmid");
    if (v2_g_pbmt !== v2_i_pbmt) rep("SplittedSRAM_2.pbmts");
    if (v2_g_ppn !== v2_i_ppn) rep("SplittedSRAM_2.ppns");
    if (v2_g_vs !== v2_i_vs) rep("SplittedSRAM_2.vs");
    if (v2_g_onlypf !== v2_i_onlypf) rep("SplittedSRAM_2.onlypf");
    if (v2_g_perm !== v2_i_perm) rep("SplittedSRAM_2.perms");
    if (v2_g_pref !== v2_i_pref) rep("SplittedSRAM_2.prefetch");
    for (int i = 0; i < 16; i++)
      if (v2_g_brdata[i] !== v2_i_brdata[i]) rep($sformatf("SplittedSRAM_2.bore_rdata[%0d]", i));
    checks++;
  endtask

  function automatic logic [V2_EW-1:0] rnd_ent_v2();
    logic [V2_EW-1:0] e;
    for (int b = 0; b < V2_EW; b++) e[b] = $urandom_range(0,1);
    return e;
  endfunction

  function automatic logic [113:0] rnd_bits_v2();
    logic [113:0] e;
    for (int b = 0; b < 114; b++) e[b] = $urandom_range(0,1);
    return e;
  endfunction

  // 随机一拍激励（含 bore 与 per-block ram_hold）
  task automatic rnd_v2();
    v2_rvalid <= ($urandom_range(0,3) != 0);
    v2_wvalid <= ($urandom_range(0,2) == 0);
    v2_rset   <= 6'($urandom);
    v2_wset   <= 6'($urandom);
    v2_waymask<= 4'($urandom);
    for (int w = 0; w < 4; w++) v2_ent[w] <= rnd_ent_v2();
    for (int i = 0; i < 16; i++) begin
      v2_baddr[i]    <= 7'($urandom ^ i);
      v2_baddr_rd[i] <= 7'($urandom ^ (i*3));
      v2_bwdata[i]   <= rnd_bits_v2() ^ 114'(i);
      v2_bwmask[i]   <= 2'($urandom);
      v2_bsel[i]     <= 1'($urandom);
      v2_barray[i]   <= 7'($urandom);
      v2_bre[i]  <= $urandom; v2_bwe[i] <= $urandom;
      v2_back[i] <= ($urandom_range(0,7) == 0);
      v2_hold[i] <= ($urandom_range(0,15) == 0);
    end
  endtask

  task automatic idle_v2();
    v2_rvalid <= 0; v2_wvalid <= 0;
    for (int i = 0; i < 16; i++) begin
      v2_bre[i] <= 0; v2_bwe[i] <= 0; v2_back[i] <= 0; v2_hold[i] <= 0;
      v2_baddr[i] <= '0; v2_baddr_rd[i] <= '0; v2_bwdata[i] <= '0;
      v2_bwmask[i] <= '0; v2_bsel[i] <= '0; v2_barray[i] <= '0;
    end
  endtask

  // ---- 覆盖率记账（对这种纯接线模块，line/branch 天然 100%，没有判别力；
  // 真正要证明的是「每一路的每一个 entry 输入位都被驱动过 1 并被读回观察过」、
  // 「waymask 全组合都出现过」、「每块 SRAM 的 hold/bore 都被单独激励过」。----
  bit [V2_EW-1:0] cov_bit_v2 [4];     // 每路每位曾被写 1
  bit [(1<<4)-1:0]       cov_wmask_v2;        // waymask 取值
  bit [64-1:0]    cov_wset_v2, cov_rset_v2;  // 写/读到过的 set
  bit [16-1:0]         cov_hold_v2, cov_back_v2;  // 逐块 hold / bore ack
  int cov_rw_same_v2, cov_rw_diff_v2;          // 同拍读写同址 / 异址
  always @(posedge clk) if (!rst) begin
    if (v2_wvalid) begin
      cov_wmask_v2[v2_waymask] <= 1;
      cov_wset_v2[v2_wset] <= 1;
      for (int w = 0; w < 4; w++)
        if (v2_waymask[w]) cov_bit_v2[w] <= cov_bit_v2[w] | v2_ent[w];
    end
    if (v2_rvalid) cov_rset_v2[v2_rset] <= 1;
    if (v2_rvalid && v2_wvalid)
      if (v2_rset == v2_wset) cov_rw_same_v2 <= cov_rw_same_v2 + 1;
      else cov_rw_diff_v2 <= cov_rw_diff_v2 + 1;
    for (int i = 0; i < 16; i++) begin
      if (v2_hold[i]) cov_hold_v2[i] <= 1;
      if (v2_back[i]) cov_back_v2[i] <= 1;
    end
  end

  task automatic cov_report_v2();
    int nb = 0;
    for (int w = 0; w < 4; w++) nb += $countones(cov_bit_v2[w]);
    $display("[COV] SplittedSRAM_2: entry 输入位写 1 覆盖 %0d/%0d（%0d 路 × %0d 位）",
             nb, 4*V2_EW, 4, V2_EW);
    $display("[COV] SplittedSRAM_2: waymask 取值 %0d/%0d  写 set %0d/64  读 set %0d/64",
             $countones(cov_wmask_v2), 1<<4, $countones(cov_wset_v2), $countones(cov_rset_v2));
    $display("[COV] SplittedSRAM_2: 逐块 ram_hold %0d/16  逐块 bore ack %0d/16  同拍读写同址 %0d 次 异址 %0d 次",
             $countones(cov_hold_v2), $countones(cov_back_v2), cov_rw_same_v2, cov_rw_diff_v2);
  endtask

  // 存储基线：把全部 64 个 set × 4 路写一遍，再整体读一遍。
  // ★为什么必须有这一步★：内层 SRAMTemplate 的 rdataReg 与厂商宏里的存储阵列都**不复位**
  //   （golden SRAMTemplate_129 只有 respReg 带异步复位）。golden 与 _xs 是两个独立实例，
  //   `+vcs+initreg+random` 给它们灌的是**互不相同**的随机上电值，于是「从没写过的地址」
  //   两侧读出来本来就不同 —— 那不是 RTL 的差异，任何正确的实现都消不掉。实测：不做这一步时
  //   seed 7/42 从 cycle 17 一直错到 cycle 4123（正好是走 1 把最后一路写到为止），而
  //   `+vcs+initreg+0` 全绿。写完之后再比，才是在比逻辑。
  task automatic initmem_v2();
    idle_v2();
    @(negedge clk);
    for (int s = 0; s < 64; s++) begin
      for (int x = 0; x < 4; x++) v2_ent[x] <= rnd_ent_v2();
      v2_wvalid <= 1; v2_wset <= 6'(s); v2_waymask <= '1; v2_rvalid <= 0;
      @(negedge clk);
    end
    v2_wvalid <= 0;
    for (int s = 0; s < 64; s++) begin
      v2_rvalid <= 1; v2_rset <= 6'(s);
      @(negedge clk);
    end
    // 同样把 MBIST 侧的 rdataReg 读一遍（bore_rdata 就是这个寄存器）
    for (int i = 0; i < 16; i++) begin
      v2_back[i] <= 1; v2_bre[i] <= 1; v2_bwe[i] <= 0; v2_baddr_rd[i] <= '0;
    end
    @(negedge clk);
    @(negedge clk);
    idle_v2();
    @(negedge clk);
  endtask

  // 定向激励：走 1 / 同拍读写 / waymask 全组合 / set 边界 / 单块 hold
  task automatic directed_v2();
    int s;
    idle_v2();
    @(negedge clk);
    // A 走 1：每路、每个 entry 输入位单独置 1，写进去再读回
    for (int w = 0; w < 4; w++)
      for (int b = 0; b < V2_EW; b++) begin
        s = (b + w) % 64;
        for (int x = 0; x < 4; x++) v2_ent[x] <= '0;
        v2_ent[w] <= (V2_EW'(1) << b);
        v2_wvalid <= 1; v2_wset <= 6'(s); v2_waymask <= 4'(1) << w;
        v2_rvalid <= 0;
        @(negedge clk);
        v2_wvalid <= 0; v2_rvalid <= 1; v2_rset <= 6'(s);
        @(negedge clk);
        @(negedge clk);
      end
    // B waymask 全组合 × set 边界；同时开读写同址
    for (int m = 0; m < (1 << 4); m++)
      foreach_set_v2(m);
    // C 逐块 ram_hold：只挡住其中一块的写，制造 slice 之间不一致
    for (int i = 0; i < 16; i++) begin
      for (int x = 0; x < 4; x++) v2_ent[x] <= rnd_ent_v2();
      for (int j = 0; j < 16; j++) v2_hold[j] <= (j == i);
      v2_wvalid <= 1; v2_waymask <= '1; v2_wset <= 6'(i % 64);
      v2_rvalid <= 1; v2_rset <= 6'(i % 64);
      @(negedge clk);
      @(negedge clk);
    end
    for (int j = 0; j < 16; j++) v2_hold[j] <= 0;
    // D 逐块 MBIST bore：一次只 ack 一块，地址/数据带块号，路由错即读出不同
    for (int i = 0; i < 16; i++) begin
      for (int j = 0; j < 16; j++) begin
        v2_back[j] <= (j == i); v2_bwe[j] <= (j == i); v2_bre[j] <= (j == i);
        v2_baddr[j] <= 7'(j + 1); v2_baddr_rd[j] <= 7'(j + 1);
        v2_bwdata[j] <= 114'(j + 1);
        v2_bwmask[j] <= '1; v2_bsel[j] <= '1;
      end
      @(negedge clk);
      @(negedge clk);
    end
    idle_v2();
    @(negedge clk);
  endtask

  task automatic foreach_set_v2(int m);
    int sets[$] = '{0, 1, 64/2, 64-1};
    foreach (sets[k]) begin
      for (int x = 0; x < 4; x++) v2_ent[x] <= rnd_ent_v2();
      v2_waymask <= 4'(m);
      v2_wvalid <= 1; v2_wset <= 6'(sets[k]);
      v2_rvalid <= 1; v2_rset <= 6'(sets[k]);   // 同拍读写同址
      @(negedge clk);
      v2_rset <= 6'((64-1) - sets[k]);  // 同拍读写异址
      @(negedge clk);
    end
  endtask

  // 逐拍比对（在时钟沿后稳定点采样）
  always @(posedge clk) if (checking) begin
    #1;
    chk_v1();
    chk_v2();
  end

  initial begin
    if ($value$plusargs("ncycles=%d", NCYCLES)) ;
    idle_v1();
    idle_v2();
    rst = 1;
    repeat (8) @(negedge clk);
    rst = 0;
    repeat (WARMUP) @(negedge clk);
    // 先把两侧存储灌成同一份确定内容，再开始比对（理由见 initmem_* 的注释）
    fork
      initmem_v1();
      initmem_v2();
    join
    checking = 1;
    fork
      directed_v1();
      directed_v2();
    join
    while (cycle < NCYCLES) begin
      rnd_v1();
      rnd_v2();
      @(negedge clk);
    end
    cov_report_v1();
    cov_report_v2();
    $display("=== SplittedSRAM UT: cycles=%0d checks=%0d errors=%0d last_err_cycle=%0d", cycle, checks, errors, last_err_cycle);
    if (errors == 0) $display("TEST PASSED");
    else $display("TEST FAILED");
    $finish;
  end
endmodule
