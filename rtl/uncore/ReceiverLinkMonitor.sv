//  验证: golden 同名模块例化本核; 6 个 flit 转换子模块(Queue4/15_CHI*+ram)两侧
//  elaborate 白盒(同 LinkMonitor); UT 双例化逐拍对拍; FM signoff-strict 签名分析。
