        // 规范地址：从某一位起向上做符号扩展或零扩展
        int unsigned top;
        top = $urandom_range(30, 49);
        for (int b = top + 1; b < 50; b++)
          io_in_bits_data_pc[b] = $urandom_range(0, 1) ? io_in_bits_data_pc[top] : 1'b0;
        if ($urandom_range(0, 1))
          for (int b = top + 1; b < 50; b++) io_in_bits_data_pc[b] = io_in_bits_data_pc[top];
      end
      // 地址空间两端：pc 贴近 0（负立即数下溢）或贴近 2^50（正偏移进位到第 50 位），
      // 这是 x4 模式下第 50 位以上出现非 0 的唯一途径
      case ($urandom_range(0, 7))
        0: io_in_bits_data_pc = 50'($urandom_range(0, 4095));
        1: io_in_bits_data_pc = ~50'($urandom_range(0, 4095));
        default: ;
      endcase
      #1;
      compare_all();
      for (int j = 0; j < NOPS; j++)
        if (io_in_bits_ctrl_fuOpType == OPS[j])
          cov_op[j][g_io_out_bits_res_redirect_bits_cfiUpdate_taken]
                   [g_io_out_bits_res_redirect_bits_cfiUpdate_isMisPred]++;
      if ($onehot(trans)) begin
        if (trans[0]) cov_fault[0][g_io_out_bits_res_redirect_bits_cfiUpdate_backendIAF]++;
        if (trans[1]) cov_fault[1][g_io_out_bits_res_redirect_bits_cfiUpdate_backendIPF]++;
        if (trans[2]) cov_fault[2][g_io_out_bits_res_redirect_bits_cfiUpdate_backendIGPF]++;
        if (trans[3]) cov_fault[3][g_io_out_bits_res_redirect_bits_cfiUpdate_backendIPF]++;
        if (trans[4]) cov_fault[4][g_io_out_bits_res_redirect_bits_cfiUpdate_backendIGPF]++;
      end
      cov_redirect[g_io_out_bits_res_redirect_valid]++;
      #1;
    end
    bad = 0; n_const = 0;
    foreach (cov_op[a, b, c]) begin
      $display("cov op=%0d taken=%0d mispred=%0d : %0d", OPS[a], b, c, cov_op[a][b][c]);
      if (cov_op[a][b][c] < NCYCLES / 1000) bad++;
    end
    foreach (cov_fault[a, b]) begin
      $display("cov trans=%0d fault=%0d : %0d", a, b, cov_fault[a][b]);
      if (cov_fault[a][b] < NCYCLES / 1000) bad++;
    end
    $display("cov redirect_valid 0/1 : %0d/%0d", cov_redirect[0], cov_redirect[1]);
    // 输出活性：golden 里恒 0 的输出恰好 79 个（Chisel 整包清零的字段 + res.data），
    // 其余 37 个必须 0/1 都见过。79 这个数是从 golden 的 assign 常量行数出来的，不是跑出来的。
    for (int o = 0; o < N_OUT; o++) begin
      if (!seen1[o]) n_const++;
      else if (!seen0[o]) begin bad++; $display("output %0d never 0", o); end
    end
    if (n_const != 79) begin bad++; $display("const-zero outputs = %0d, expect 79", n_const); end
    $display("checks=%0d errors=%0d bad_cov=%0d const_zero_outs=%0d", checks, errors, bad, n_const);
    if (errors == 0 && checks > 1000 && bad == 0) $display("TEST PASSED");
    else $display("TEST FAILED");
    $finish;
  end
