#!/usr/bin/env python3
"""test_port_contract_lint.py —— 端口契约闸的负测。

本工程有过"测试假通过"的教训（三个断言全被前置的 dirty 门挡掉了，测试却报 PASS）。
所以这里的结构是**变异测试**：

  1. 先立一个"两侧完全对齐"的基准夹具，断言它 **PASS**（正控制）。
     —— 这一条要是不过，后面所有 FAIL 断言都没有意义，直接终止。
  2. 每条负测都是在**同一个基准夹具**上只改一处（改位宽 / 反方向 / 删端口 /
     加端口 / 改 unpacked 维 / 加 signed ...），断言它 **FAIL**，
     并且断言失败原因里含**预期关键字**（PACKED / DIR / MISSING / ...）。
     只改一处 + 关键字断言，保证被测的确实是那条判据，而不是被别的检查提前拦下。
  3. 另有若干"解析失败必须 FAIL 而非放行"的畸形输入用例。
  4. 真实回归：拿仓库现有的 ICacheCtrlUnit / NewPipelineConnectPipe_33 当样本，
     断言 lint 确实报错（这两个是今天真出事的目标）。

跑法：  python3 scripts/test_port_contract_lint.py
退出码 0 = 全通过；非 0 = 有用例没达到预期。
"""

import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
LINT = os.path.join(HERE, 'port_contract_lint.py')
G1 = os.environ.get('GOLDEN_RTL', '/home/eda/xs-env/G1-canonical/golden-rtl')

# ---------------------------------------------------------------------------
# 基准夹具：golden 侧照 firtool 风格写，impl 侧故意换一种可读风格
# （logic / 对齐方式不同 / 带注释）—— 这些差异**不该**触发失败，
# 否则闸会在真实工程里到处误伤。
# ---------------------------------------------------------------------------
GOLDEN_BASE = """// Generated by CIRCT firtool-1.62.1
module Foo(
  input         clock,
  input         reset,
  output        io_out_ready,
  input         io_in_valid,
  input  [2:0]  io_in_bits_source,
  input  [63:0] io_in_bits_data,
  output [1:0]  io_out_bits_param,
  input         io_flush
);
  assign io_out_ready = 1'h1;
  assign io_out_bits_param = 2'h0;
endmodule
"""

IMPL_BASE = """// 可读重写：风格与 golden 不同（logic / 注释 / 对齐），端口契约必须一致
module Foo(
  input  logic        clock,
  input  logic        reset,       // 同步复位
  output logic        io_out_ready,
  input  logic        io_in_valid,
  input  logic [2:0]  io_in_bits_source,
  input  logic [63:0] io_in_bits_data,
  output logic [1:0]  io_out_bits_param,
  input  logic        io_flush
);
  assign io_out_ready     = 1'b1;
  assign io_out_bits_param = '0;
endmodule
"""


class Failure(Exception):
    pass


RESULTS = []
SKIPPED = []   # (用例名, 原因) —— 跳过的用例**不算通过**，汇总里单列


def run_lint(tmp, targets, extra=None, impl='impl.sv'):
    args = [sys.executable, LINT,
            '--golden-dir', os.path.join(tmp, 'golden'),
            '--rtl-root', os.path.join(tmp, 'rtl'),
            '--max-diff', '0']
    if impl:
        args += ['--impl-src', os.path.join(tmp, 'rtl', impl)]
    args += (extra or [])
    args += targets
    p = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                       universal_newlines=True)
    return p.returncode, p.stdout


def make_fixture(golden=GOLDEN_BASE, impl=IMPL_BASE, gname='Foo.sv',
                 iname='impl.sv'):
    tmp = tempfile.mkdtemp(prefix='portlint_test_')
    os.makedirs(os.path.join(tmp, 'golden'))
    os.makedirs(os.path.join(tmp, 'rtl'))
    with open(os.path.join(tmp, 'golden', gname), 'w') as f:
        f.write(golden)
    with open(os.path.join(tmp, 'rtl', iname), 'w') as f:
        f.write(impl)
    return tmp


def check(name, cond, detail=''):
    RESULTS.append((name, bool(cond), detail))
    print('%-4s %s' % ('ok' if cond else 'FAIL', name))
    if not cond and detail:
        for line in detail.strip().splitlines():
            print('       | ' + line)


def expect_pass(name, golden=GOLDEN_BASE, impl=IMPL_BASE, extra=None,
                targets=('Foo',)):
    tmp = make_fixture(golden, impl)
    try:
        rc, out = run_lint(tmp, list(targets), extra)
        check(name, rc == 0 and '[PASS]' in out, 'rc=%d\n%s' % (rc, out))
        return rc, out
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def expect_fail(name, keyword, golden=GOLDEN_BASE, impl=IMPL_BASE, extra=None,
                targets=('Foo',), impl_arg='impl.sv'):
    """必须非零退出，且输出里出现 keyword（证明命中的是**预期那条判据**）。"""
    tmp = make_fixture(golden, impl)
    try:
        rc, out = run_lint(tmp, list(targets), extra, impl=impl_arg)
        ok = (rc != 0) and (keyword in out)
        why = ''
        if rc == 0:
            why = '期望 FAIL 却 rc=0（放行了！）'
        elif keyword not in out:
            why = '虽然 FAIL 了，但原因里没有预期关键字 %r —— 可能是被别的检查' \
                  '提前拦下，本条判据其实没被执行到' % keyword
        check(name, ok, (why + '\n' + out) if not ok else '')
        return rc, out
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# ---------------------------------------------------------------------------
# 家族参数 core 的 invariant 负测（codex 0145 §2 / 0146 验收清单最后一条）
#
# 被测对象：rtl/memblock/xs_TLBuffer_ad_core.sv —— 5 个 TLBuffer 变体共用的参数化
# 核，里面有"载荷宽度等式"自检（A_PAYLOAD_W 必须等于 golden 队列的 ram_2x<N> 的 N）。
# 这就是今天那起事故的防呆点：SOURCE_W 停在 G0 的旧值上，逻辑一行都不会错，随机激励
# 也未必打得到高位，只有这条等式会当场炸。
#
# 负测做法：拿 TLBuffer_6 的真实参数各造一次 —— 一次全对（必须跑过），一次只把
# SOURCE_W 从 4 改回 G0 的 3（必须 $fatal）。**两次都做**，不然"必失败"可能只是
# 因为这个夹具压根就编不过。
#
# 老实说明：这条 invariant 现在写在 `initial` 里，是**仿真 t=0** 触发，不是严格
# 意义上的 elaborate-time（SV 的 elaboration system task 要把 $fatal 直接写在
# 模块体里而不是 initial 里）。所以它挡得住 UT，挡不住纯 elaborate/综合流程。
# 这属于 RTL 侧的改法，不在本 owner 的文件范围内，只如实记录。
# ---------------------------------------------------------------------------
CORE = os.path.join(REPO, 'rtl/memblock/xs_TLBuffer_ad_core.sv')

TB_INVARIANT = """// 只为触发 xs_TLBuffer_ad_core 的宽度等式自检；端口全不接。
module tb;
  xs_TLBuffer_ad_core #(
    .A_SIZE_W(3), .D_SIZE_W(3), .SOURCE_W(%(src)d), .ADDR_W(48),
    .MASK_W(32), .DATA_W(256), .D_SINK_W(10), .A_USER_W(5),
    .A_RAM_WIDTH(356), .D_RAM_WIDTH(281)
  ) dut ();
  initial begin
    #1;
    $display("NO_FATAL_REACHED");
    $finish;
  end
endmodule
"""


def _mem_available_gb():
    try:
        for line in open('/proc/meminfo'):
            if line.startswith('MemAvailable:'):
                return int(line.split()[1]) // (1024 * 1024)
    except OSError:
        pass
    return -1


def invariant_cases():
    if not os.path.exists(CORE):
        SKIPPED.append(('invariant', '家族 core 不在: %s' % CORE))
        print('     （跳过：%s 不存在）' % CORE)
        return
    if shutil.which('vcs') is None:
        SKIPPED.append(('invariant', '本机没有 vcs，无法验证 elaborate/仿真期自检'))
        print('     （跳过：找不到 vcs）')
        return
    avail = _mem_available_gb()
    if 0 <= avail < 20:
        SKIPPED.append(('invariant', '可用内存只有 %d GB (<20)，按纪律不起 VCS' % avail))
        print('     （跳过：可用内存 %d GB < 20 GB）' % avail)
        return

    env = dict(os.environ)
    env['VCS_ARCH_OVERRIDE'] = 'linux'

    def one(label, src_w, expect_fatal):
        tmp = tempfile.mkdtemp(prefix='portlint_inv_')
        try:
            tb = os.path.join(tmp, 'tb.sv')
            with open(tb, 'w') as f:
                f.write(TB_INVARIANT % {'src': src_w})
            cmp_ = subprocess.run(
                ['vcs', '-full64', '-sverilog', '-timescale=1ns/1ps',
                 '+define+SYNTHESIS', CORE, tb, '-top', 'tb', '-o', 'simv'],
                cwd=tmp, env=env, stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, universal_newlines=True)
            out = cmp_.stdout
            rc = cmp_.returncode
            if rc == 0:
                sim = subprocess.run([os.path.join(tmp, 'simv')], cwd=tmp,
                                     env=env, stdout=subprocess.PIPE,
                                     stderr=subprocess.STDOUT,
                                     universal_newlines=True)
                out += sim.stdout
                rc = sim.returncode
            fatal = ('xs_TLBuffer_ad_core:' in out) or ('Fatal' in out)
            reached = 'NO_FATAL_REACHED' in out
            if expect_fatal:
                ok = fatal and not reached
                why = ('期望 invariant 触发但没触发（fatal=%s reached=%s）'
                       % (fatal, reached))
            else:
                ok = reached and not fatal
                why = ('正确参数下不该报错，但 fatal=%s reached=%s'
                       % (fatal, reached))
            check(label, ok, '' if ok else why + '\n' + out[-3000:])
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    # 正控制：TLBuffer_6 的真实参数（SOURCE_W=4）必须跑过。
    # 没有这条，下面那条"必失败"可能只是夹具本身编不过，等于假通过。
    one('invariant positive-control: TLBuffer_6 正确参数 (SOURCE_W=4) 必须不报错',
        4, False)
    # 负测：SOURCE_W 停在 G0 的 3 —— 正是今天那起事故的形态
    one('invariant: SOURCE_W 写回 G0 旧值 3 -> 载荷宽度等式必须 $fatal',
        3, True)


# ---------------------------------------------------------------------------
# ut_common.mk 接线的行为测试（codex 0146："FM_VARIANTS 为空只能显式 SKIP，
# 不能产生 signoff receipt"）
#
# 造一个只 include ut_common.mk 的临时 UT 目录，分别验：
#   (a) FM_VARIANTS 为空  -> make portlint 显式打 [SKIP] 且退出 0（不静默通过）
#   (b) FM_VARIANTS 为空  -> make fm 必须失败（不产生 receipt）
#   (c) 未声明的顶层      -> make fm-<未声明> 必须被守卫拦下（不产生 receipt）
#
# (b)(c) 用被裁剪过的 PATH 跑：即便守卫写错了，fm_shell 也不在 PATH 里，
# 绝无可能真的起一次 FM（本任务硬约束：不许跑 fm_shell）。
# ---------------------------------------------------------------------------
UT_MK = os.path.join(HERE, 'ut_common.mk')

MK_TEMPLATE = """MODULE = PortlintProbe
RTL_SRCS =
TB_SRCS =
GOLDEN_SRCS =
FM_VARIANTS = %(variants)s
XSSV_HOME = %(home)s
include %(utmk)s
"""


def _mk(tmp, variants):
    with open(os.path.join(tmp, 'Makefile'), 'w') as f:
        f.write(MK_TEMPLATE % {'variants': variants, 'home': REPO,
                               'utmk': UT_MK})


SAFE_PATH = '/usr/bin:/bin'


def _fm_shell_unreachable():
    """确认在 SAFE_PATH 下确实找不到 fm_shell —— 找得到就不许跑这些用例
    （本任务硬约束：绝不能起一次 fm_shell）。"""
    return shutil.which('fm_shell', path=SAFE_PATH) is None


def _run_make(tmp, target, safe_path=False):
    env = dict(os.environ)
    if safe_path:
        env['PATH'] = SAFE_PATH
    p = subprocess.run(['make', '-C', tmp, target, '--no-print-directory'],
                       env=env, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, universal_newlines=True)
    return p.returncode, p.stdout


def ut_common_cases():
    if shutil.which('make') is None:
        SKIPPED.append(('ut_common', '本机没有 make'))
        print('     （跳过：找不到 make）')
        return

    # (a) 空 FM_VARIANTS -> 显式 SKIP，退出 0
    tmp = tempfile.mkdtemp(prefix='portlint_mk_')
    try:
        _mk(tmp, '')
        rc, out = _run_make(tmp, 'portlint')
        check('ut_common: FM_VARIANTS 为空 -> portlint 显式 [SKIP]（不静默通过）',
              rc == 0 and '[SKIP]' in out and 'signoff receipt' in out,
              'rc=%d\n%s' % (rc, out))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if not _fm_shell_unreachable():
        SKIPPED.append(('ut_common fm 守卫',
                        'SAFE_PATH 下能找到 fm_shell，为不误起 FM 而跳过'))
        print('     （跳过 fm 守卫用例：SAFE_PATH 下能找到 fm_shell）')
        return

    tmp = tempfile.mkdtemp(prefix='portlint_mk_')
    try:
        _mk(tmp, '')
        # (b) 空 FM_VARIANTS -> make fm 必须失败，不能出 receipt
        rc, out = _run_make(tmp, 'fm', safe_path=True)
        check('ut_common: FM_VARIANTS 为空 -> make fm 必须失败（不出 receipt）',
              rc != 0 and '无 FM_VARIANTS' in out, 'rc=%d\n%s' % (rc, out))
        # (c) 空 FM_VARIANTS 下直接点名一个顶层 -> 守卫必须拦
        rc, out = _run_make(tmp, 'fm-Whatever', safe_path=True)
        check('ut_common: 空 FM_VARIANTS 下 make fm-<顶层> 必须被守卫拦下',
              rc != 0 and '不在 FM_VARIANTS' in out, 'rc=%d\n%s' % (rc, out))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    # (d) 有 FM_VARIANTS 时，未声明的顶层同样拦；已声明的顶层放行到下一步
    tmp = tempfile.mkdtemp(prefix='portlint_mk_')
    try:
        _mk(tmp, 'Declared')
        rc, out = _run_make(tmp, 'fm-Undeclared', safe_path=True)
        check('ut_common: 顶层不在 FM_VARIANTS 里 -> fm-% 守卫必须拦下',
              rc != 0 and '不在 FM_VARIANTS' in out, 'rc=%d\n%s' % (rc, out))
        rc, out = _run_make(tmp, 'fm-Declared', safe_path=True)
        # 已声明的顶层要能过守卫（之后会因为 PATH 里没有 fm_shell 而失败，
        # 那正说明守卫放行了、没有在守卫这一步就挂）
        check('ut_common positive-control: 已声明顶层能过守卫（不被误拦）',
              '不在 FM_VARIANTS' not in out, 'rc=%d\n%s' % (rc, out))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


