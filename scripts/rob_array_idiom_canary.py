#!/usr/bin/env python3
"""rob_array_idiom_canary.py -- which entry-array idiom survives Formality
elaborate when the array depth is NOT a power of two?

Why this exists
---------------
Rob has RobSize=160 entries. The obvious readable rewrite is an array indexed
by a pointer -- `ent_pdest[deqPtr]`. At depth 160 with an 8-bit index,
Formality raises FMR_ELAB-147 ("Index may take values outside array bound") and
`set_top` FAILS. Not a warning to live with: the proof does not start.

The previous round (xs-v2r2-sv) hit the downstream version of this: its core
stored entries as a packed struct, so the only impl DFF objects Formality could
see were `rob_entries_reg[N][bit]` with `bit` an offset into a 201-bit
concatenation. `set_user_match` could not address them -- FM-036 on 9263/9440 --
so name-pinning was unavailable and signature matching had to carry the whole
load. That is what left Rob as the only non-SIGNOFF_PASS target in the 306.

So before writing a single line of the core, measure which idiom works.

Two-sided by construction
-------------------------
CONVENTIONS: a check that only ever fires proves nothing. This runs FIVE impl
layouts against one golden-shaped reference and asserts the FULL pattern --
four MUST fail elaborate, one MUST pass and verify. A layout silently starting
to pass (or the working one starting to fail) breaks --check.

  ref        firtool-style flat scalars `ent_<i>_<field>` (what golden emits)
  soa        unpacked per-field array, signal index          expect ELAB-147
  soa_guard  same, bound guard hoisted into always_comb      expect ELAB-147
  aos        packed struct array, signal index (prev round)  expect ELAB-147
  packed     packed per-field vector, `[idx*w +: w]`         expect ELAB-147
  soamux     unpacked per-field array, LOOP index            expect SUCCEEDED

`soa_guard` is the interesting negative: CONVENTIONS' stated fix for ELAB-147 is
"把守卫提出来，先算下标再索引". That works when the guard narrows a select. It
does NOT work here, because ELAB-147 is decided on the index's DECLARED WIDTH,
not on any provable value range -- an 8-bit signal against a 160-deep array is
flagged however it was computed. Only the loop form, where the index is a loop
variable the loop itself bounds, avoids it. That is also golden's own shape:
firtool emits a 160-way equality mux.

Measured baseline (2026-09-18, fm_shell V-2023.12-SP3, N=160, 1280 registers)

  layout      verdict     ELAB147   match_s  verify_s  points
  soa         ELAB147          11         -         -       -
  soa_guard   ELAB147          11         -         -       -
  aos         ELAB147          11         -         -       -
  packed      ELAB147           7         -         -       -
  soamux      SUCCEEDED         0       147        40    4025      peak 1676 MB

With all 4000 registers name-pinned (pin map generated by a nested loop from
`gen_rob.py --regmap`, not hand-written): 4000/4000 pins ACCEPTED, no FM-036,
match 147 s -> 55 s, same 4025 passing, SUCCEEDED.

Match scaling for `soamux`, unpinned (this is why the layout matters at Rob's
size -- 11,639 registers is 9x the largest point here):

  regs   match_s  verify_s  peak_MB   segment exponent
   320         8         4      867   -
   640        33        12      974   2.04
  1280       147        40     1676   2.16
  2560       554       161     4412   1.91
  overall 320->2560                   2.04      i.e. match is ~O(N^2)

  extrapolated to Rob's 11,639 registers: 2.8 h (e=1.91) .. 3.4 h (e=2.04).

★Two limits on those extrapolations, do not quote them without these★
  * Only the EXPONENT transfers. The constant does not: this canary has 8
    fields with a trivial update, Rob has 36+ fields with real logic.
  * The peak_MB column does NOT transfer at all -- its exponent climbs
    (0.17 -> 0.78 -> 1.40) because THIS canary's reference reads through an
    N-deep equality mux chain per field, so its combinational size grows as
    O(N^2). Golden Rob reads through 8 banks x a 20-row one-hot address, which
    is O(N). Extrapolating memory from here would overstate Rob.

Usage
  python3 scripts/rob_array_idiom_canary.py --run [--dir D] [--n 160]
  python3 scripts/rob_array_idiom_canary.py --check   # run + assert the pattern
  python3 scripts/rob_array_idiom_canary.py --run --n 320   # a scaling point
"""
import argparse, os, re, subprocess, sys, tempfile

FIELDS = [('valid', 1), ('uopNum', 4), ('pdest', 8), ('fflags', 5),
          ('vxsat', 1), ('isRVC', 1), ('ftqOffset', 4), ('interrupt_safe', 1)]

EXPECT = {'soa': 'ELAB147', 'soa_guard': 'ELAB147', 'aos': 'ELAB147',
          'packed': 'ELAB147', 'soamux': 'SUCCEEDED'}


def decl(w):
    return '[%d:0] ' % (w - 1) if w > 1 else ''


def head(aw):
    p = ['  input  logic clock, input logic reset,',
         '  input  logic [%d:0] widx, input logic wen,' % (aw - 1)]
    for f, w in FIELDS:
        p.append('  input  logic %sw_%s,' % (decl(w), f))
    p.append('  input  logic [%d:0] ridx,' % (aw - 1))
    for k, (f, w) in enumerate(FIELDS):
        p.append('  output logic %sr_%s%s'
                 % (decl(w), f, ',' if k < len(FIELDS) - 1 else ''))
    return 'module Canary(\n' + '\n'.join(p) + '\n);'


def gen_ref(n, aw):
    """Golden's shape: one scalar reg per (entry, field), a 160-way mux to read.
    The mux chain ends at entry 0 (not a literal) so every impl below is
    functionally identical to it and the canary measures MATCHING, not a
    behaviour delta."""
    L = ['module Canary(', '  input clock,', '  input reset,',
         '  input [%d:0] widx,' % (aw - 1), '  input wen,']
    for f, w in FIELDS:
        L.append('  input %sw_%s,' % (decl(w), f))
    L.append('  input [%d:0] ridx,' % (aw - 1))
    for k, (f, w) in enumerate(FIELDS):
        L.append('  output %sr_%s%s'
                 % (decl(w), f, ',' if k < len(FIELDS) - 1 else ''))
    L.append(');')
    for i in range(n):
        for f, w in FIELDS:
            L.append('  reg %sent_%d_%s;' % (decl(w), i, f))
    for i in range(n):
        L += ['  always @(posedge clock) begin',
              "    if (reset) begin ent_%d_valid <= 1'h0; end" % i,
              "    else if (wen & widx == %d'h%x) begin" % (aw, i)]
        for f, w in FIELDS:
            L.append('      ent_%d_%s <= w_%s;' % (i, f, f))
        L += ['    end', '  end']
    for f, w in FIELDS:
        e = 'ent_0_%s' % f
        for i in reversed(range(1, n)):
            e = "ridx == %d'h%x ? ent_%d_%s : %s" % (aw, i, i, f, e)
        L.append('  assign r_%s = %s;' % (f, e))
    L.append('endmodule')
    return '\n'.join(L) + '\n'


def gen_impl(kind, n, aw):
    h = head(aw)
    if kind in ('soa', 'soa_guard'):
        s = [h]
        for f, w in FIELDS:
            s.append('  logic %sent_%s [%d];' % (decl(w), f, n))
        wi, ri = 'widx', 'ridx'
        if kind == 'soa_guard':
            s += ['  logic [%d:0] widx_b, ridx_b;' % (aw - 1),
                  '  always_comb begin',
                  "    widx_b = (widx < %d) ? widx : '0;" % n,
                  "    ridx_b = (ridx < %d) ? ridx : '0;" % n,
                  '  end']
            wi, ri = 'widx_b', 'ridx_b'
        s += ['  always_ff @(posedge clock) begin',
              "    if (reset) for (int i = 0; i < %d; i++) ent_valid[i] <= 1'b0;" % n,
              '    else if (wen) begin']
        for f, w in FIELDS:
            s.append('      ent_%s[%s] <= w_%s;' % (f, wi, f))
        s += ['    end', '  end']
        for f, w in FIELDS:
            s.append('  assign r_%s = ent_%s[%s];' % (f, f, ri))
        s.append('endmodule')
        return '\n'.join(s) + '\n'
    if kind == 'aos':
        a = ['package cpkg;', '  typedef struct packed {']
        for f, w in reversed(FIELDS):
            a.append('    logic %s%s;' % (decl(w), f))
        a += ['  } ent_t;', 'endpackage',
              h.replace('module Canary(', 'module Canary import cpkg::*; ('),
              '  ent_t ent_q [%d];' % n,
              '  always_ff @(posedge clock) begin',
              "    if (reset) for (int i = 0; i < %d; i++) ent_q[i].valid <= 1'b0;" % n,
              '    else if (wen) begin']
        for f, w in FIELDS:
            a.append('      ent_q[widx].%s <= w_%s;' % (f, f))
        a += ['    end', '  end']
        for f, w in FIELDS:
            a.append('  assign r_%s = ent_q[ridx].%s;' % (f, f))
        a.append('endmodule')
        return '\n'.join(a) + '\n'
    if kind == 'packed':
        p = [h]
        for f, w in FIELDS:
            p.append('  logic [%d:0] ent_%s;' % (n * w - 1, f))
        p += ['  always_ff @(posedge clock) begin',
              "    if (reset) ent_valid <= '0;", '    else if (wen) begin']
        for f, w in FIELDS:
            p.append('      ent_%s[widx] <= w_%s;' % (f, f) if w == 1 else
                     '      ent_%s[widx*%d +: %d] <= w_%s;' % (f, w, w, f))
        p += ['    end', '  end']
        for f, w in FIELDS:
            p.append('  assign r_%s = ent_%s[ridx];' % (f, f) if w == 1 else
                     '  assign r_%s = ent_%s[ridx*%d +: %d];' % (f, f, w, w))
        p.append('endmodule')
        return '\n'.join(p) + '\n'
    if kind == 'soamux':
        s = [h]
        for f, w in FIELDS:
            s.append('  logic %sent_%s [%d];' % (decl(w), f, n))
        s += ['  always_ff @(posedge clock) begin', '    if (reset) begin',
              "      for (int i = 0; i < %d; i++) ent_valid[i] <= 1'b0;" % n,
              '    end else if (wen) begin',
              '      for (int i = 0; i < %d; i++) begin' % n,
              "        if (widx == %d'(i)) begin" % aw]
        for f, w in FIELDS:
            s.append('          ent_%s[i] <= w_%s;' % (f, f))
        s += ['        end', '      end', '    end', '  end', '',
              '  always_comb begin']
        for f, w in FIELDS:
            s.append('    r_%s = ent_%s[0];' % (f, f))
        s += ['    for (int i = 1; i < %d; i++) begin' % n,
              "      if (ridx == %d'(i)) begin" % aw]
        for f, w in FIELDS:
            s.append('        r_%s = ent_%s[i];' % (f, f))
        s += ['      end', '    end', '  end', 'endmodule']
        return '\n'.join(s) + '\n'
    raise SystemExit('unknown kind %s' % kind)


TCL = """set implf $env(CANARY_IMPL)
set_app_var verification_merge_duplicated_registers true
read_sverilog -container r -libname WORK -05 ./Canary_ref.sv
set_top r:/WORK/Canary
read_sverilog -container i -libname WORK $implf
set_top i:/WORK/Canary
set t0 [clock seconds]
match
set t1 [clock seconds]
puts "CANARY_MATCH_SEC [expr {$t1-$t0}]"
verify
set t2 [clock seconds]
puts "CANARY_VERIFY_SEC [expr {$t2-$t1}]"
exit 0
"""


def run_one(d, kind):
    log = os.path.join(d, 'log_%s.txt' % kind)
    env = dict(os.environ, CANARY_IMPL='./Canary_%s.sv' % kind)
    with open(log, 'w') as f:
        subprocess.call(['fm_shell', '-64', '-work_path',
                         os.path.join(d, 'fmw_%s' % kind),
                         '-file', os.path.join(d, 'canary.tcl')],
                        cwd=d, stdin=subprocess.DEVNULL, stdout=f,
                        stderr=subprocess.STDOUT, env=env)
    txt = open(log).read()
    elab147 = txt.count('FMR_ELAB-147')
    ok = 'Verification SUCCEEDED' in txt
    m = re.search(r'CANARY_MATCH_SEC (\d+)', txt)
    v = re.search(r'CANARY_VERIFY_SEC (\d+)', txt)
    pts = re.search(r'^\s*(\d+) Passing compare points', txt, re.M)
    verdict = 'SUCCEEDED' if ok else ('ELAB147' if elab147 else 'OTHER_FAIL')
    return dict(kind=kind, verdict=verdict, elab147=elab147,
                match_s=int(m.group(1)) if m else None,
                verify_s=int(v.group(1)) if v else None,
                points=int(pts.group(1)) if pts else None, log=log)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=160)
    ap.add_argument('--dir')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--run', action='store_true')
    a = ap.parse_args()
    if not (a.check or a.run):
        ap.error('pick --run or --check')
    d = a.dir or tempfile.mkdtemp(prefix='rob-idiom-canary-')
    os.makedirs(d, exist_ok=True)
    aw = (a.n - 1).bit_length()
    open(os.path.join(d, 'Canary_ref.sv'), 'w').write(gen_ref(a.n, aw))
    for k in EXPECT:
        open(os.path.join(d, 'Canary_%s.sv' % k), 'w').write(gen_impl(k, a.n, aw))
    open(os.path.join(d, 'canary.tcl'), 'w').write(TCL)
    print('# dir %s   N=%d   regs=%d' % (d, a.n, a.n * len(FIELDS)))
    print('%-10s %-10s %-8s %8s %8s %8s' %
          ('layout', 'verdict', 'elab147', 'match_s', 'verify_s', 'points'))
    bad = []
    for k in sorted(EXPECT):
        r = run_one(d, k)
        print('%-10s %-10s %-8d %8s %8s %8s' %
              (r['kind'], r['verdict'], r['elab147'],
               r['match_s'], r['verify_s'], r['points']))
        if r['verdict'] != EXPECT[k]:
            bad.append('%s: expected %s got %s (%s)'
                       % (k, EXPECT[k], r['verdict'], r['log']))
    if a.check:
        if bad:
            print('CANARY CHECK FAILED:', file=sys.stderr)
            for b in bad:
                print('  ' + b, file=sys.stderr)
            return 1
        print('CANARY CHECK OK (4 must-fail failed, 1 must-pass passed)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
