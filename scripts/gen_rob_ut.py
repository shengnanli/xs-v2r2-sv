def selftest(ports):
    ins = [p for p in ports if p[0] == 'input']
    outs = [p for p in ports if p[0] == 'output']
    rows = [
        ('port_total', len(ports) == 2200, '2200 ports parsed (measured)'),
        ('split', len(ins) == 1533 and len(outs) == 667,
         '1533 in / 667 out'),
        ('no_dup', len({p[3] for p in ports}) == len(ports),
         'no duplicate port name'),
        ('enq_present', any(p[3] == 'io_enq_req_0_bits_firstUop' for p in ports),
         'the warm-up handle exists'),
        ('canaccept_is_output',
         any(p[0] == 'output' and p[3] == 'io_enq_canAccept' for p in ports),
         'io_enq_canAccept is an OUTPUT -- Rob decides acceptance, tb cannot force it'),
    ]
    ok = True
    for name, good, why in rows:
        print('%-22s %-5s %s' % (name, 'OK' if good else 'FAIL', why))
        ok &= good
    return 0 if ok else 1



def _target_absent_is_expected(target, module):
    """目标文件不存在时，判断这是不是**预期内**的（核还没建），并给出退出码。

    ★不许 fail-open★：目标不在就无脑返回 0，等于"删掉产物即可让闸变绿"。
    所以要和台账交叉核对：docs/coverage_three_axis.tsv 里该模块若是 MISSING，
    说明核确实还没写（本仓刻意不建空壳 —— 上一轮那个驱动 0 个输出的 SCAFFOLD
    就是这么骗过台账一整轮的），此时"无可比对"是事实；
    若台账说已 REWRITTEN 而文件却不见了，那就是真出事了，必须红。
    """
    import io, os
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    led = os.path.join(repo, 'docs', 'coverage_three_axis.tsv')
    status = None
    try:
        with io.open(led, encoding='utf-8') as f:
            for line in f:
                if line.startswith('#'):
                    continue
                p = line.rstrip('\n').split('\t')
                if len(p) >= 2 and p[0] == module:
                    status = p[1].strip()
                    break
    except IOError:
        pass
    if status == 'MISSING':
        sys.stderr.write(
            '%s --check: 目标 %s 尚未建立，台账也记着 MISSING —— 无可比对，视为通过。\n'
            % (module, target))
        sys.stderr.write(
            '  （核落地后本条会自动变成真正的逐字节比对；此处不 fail-open：\n'
            '   台账若已记 REWRITTEN 而文件不见，本闸会红。）\n')
        return 0
    sys.stderr.write(
        '%s --check: 目标 %s 不存在，而台账状态是 %s（不是 MISSING）—— 判失败。\n'
        % (module, target, status))
    return 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--golden', default=GOLDEN)
    ap.add_argument('--emit')
    # nargs='?' + 默认值：让无参 `--check` 也能用，好进 gate_all 的统一列表。
    # 目标不存在时走 _target_absent_is_expected（与台账交叉核对，不 fail-open）。
    ap.add_argument('--check', nargs='?', const='__default__', default=None)
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('--emit-makefile', dest='emit_makefile')
    a = ap.parse_args()
    ports, digest = parse(a.golden)
    if a.selftest:
        return selftest(ports)
    body = build(ports, digest)
    if a.check:
        import os as _os
        tgt = a.check
        if tgt == '__default__':
            # 无参 --check：默认目标是 Rob 的 UT tb。核还没建时它不存在，
            # 走与 gen_rob.py 相同的降级判据（与台账交叉核对，不 fail-open）。
            tgt = _os.path.join(_os.path.dirname(_os.path.dirname(
                _os.path.abspath(__file__))), 'verif', 'ut', 'Rob', 'tb.sv')
        if not _os.path.exists(tgt):
            return _target_absent_is_expected(tgt, 'Rob')
        with open(tgt) as f:
            cur = f.read()
        same = cur == body
        print('gen_rob_ut --check: %s' % ('OK' if same else 'DRIFT'))
        return 0 if same else 1
    if a.emit_makefile:
        os.makedirs(os.path.dirname(os.path.abspath(a.emit_makefile)), exist_ok=True)
        with open(a.emit_makefile, 'w') as f:
            f.write(MAKEFILE)
        print('wrote %s' % a.emit_makefile, file=sys.stderr)
        return 0
    if a.emit:
        os.makedirs(os.path.dirname(os.path.abspath(a.emit)), exist_ok=True)
        with open(a.emit, 'w') as f:
            f.write(body)
        print('wrote %s (%d lines)' % (a.emit, body.count('\n')), file=sys.stderr)
        return 0
    sys.stdout.write(body)
    return 0


if __name__ == '__main__':
    sys.exit(main())
