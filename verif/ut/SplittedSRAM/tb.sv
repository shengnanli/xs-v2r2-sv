    for (int i = 0; i < 1; i++) begin
      v1_baddr[i]    <= 3'($urandom ^ i);
      v1_baddr_rd[i] <= 3'($urandom ^ (i*3));
      v1_bwdata[i]   <= rnd_bits_v1() ^ 131'(i);
      v1_bwmask[i]   <= 1'($urandom);
      v1_bsel[i]     <= 6'($urandom);
      v1_barray[i]   <= 6'($urandom);
      v1_bre[i]  <= $urandom; v1_bwe[i] <= $urandom;
      v1_back[i] <= ($urandom_range(0,7) == 0);
      v1_hold[i] <= ($urandom_range(0,15) == 0);
    end
  endtask

  task automatic idle_v1();
    v1_rvalid <= 0; v1_wvalid <= 0;
    for (int i = 0; i < 1; i++) begin
      v1_bre[i] <= 0; v1_bwe[i] <= 0; v1_back[i] <= 0; v1_hold[i] <= 0;
      v1_baddr[i] <= '0; v1_baddr_rd[i] <= '0; v1_bwdata[i] <= '0;
