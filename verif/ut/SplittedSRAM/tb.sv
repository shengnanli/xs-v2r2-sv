             $countones(cov_wmask_v1), 1<<2, $countones(cov_wset_v1), $countones(cov_rset_v1));
    $display("[COV] SplittedSRAM_1: 逐块 ram_hold %0d/1  逐块 bore ack %0d/1  同拍读写同址 %0d 次 异址 %0d 次",
