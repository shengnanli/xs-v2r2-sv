// =============================================================================
// TLBuffer_13 —— L2 入口的 4 路 TL-C 五通道时序缓冲（L2Top.inner_buffer）
//
// 位置：L2Top 里核侧 TileLink（L1 DCache/ICache 等经 xbar 汇过来）进入 4 个 L2 slice
//   之前的一级打拍站。rocket-chip TLBuffer(BufferParams.default) 作用在 4 条 bank 化的
//   TL-C 链路上，每条链路 A/B/C/D/E 五个通道各串一个 Queue(entries=2, pipe=false,
//   flow=false)。目的只有一个：切断 ready/valid 的长组合路径，代价每通道一拍延迟。
//   本层不解码 opcode/param、不跨通道重排，单通道严格保序。
//
// 结构：4 个 bank 完全相同（golden 里平铺成 20 个 Queue2、374 个端口）。本文件：
//   xs_TLBuffer_13_bank   手写：一条 TL-C 链路的五通道缓冲（5 个 Queue2）。
//   TLBuffer_13           生成（scripts/gen_tlbuffer13.py，带 --check）：golden 同名端口表
//                         + 4 个 bank 例化，auto_<in|out>_<b>_<x> 接 bank b 的 <in|out>_<x>。
//
// 端口方向（client = 上游核侧 = auto_in_*，manager = 下游 L2 slice 侧 = auto_out_*）：
//   A  client -> manager  enq=in_a  deq=out_a      B  manager -> client  enq=out_b deq=in_b
//   C  client -> manager  enq=in_c  deq=out_c      D  manager -> client  enq=out_d deq=in_d
//   E  client -> manager  enq=in_e  deq=out_e
//
// 队列：本仓已签的重写件 rtl/uncore/Queue2_TLBundle{A_19,B_1,C_1,D_20,E_1}.sv（控制逻辑在
//   rtl/common/xs_ChiselQueue_core.sv）。它们的存储 ram_2x119 / ram_2x352 / ram_2x321 /
//   ram_2x283 / ram_sink_2x8 是 firtool 行为级叶子（无复位、2 项、组合读），两侧读同一份
//   golden 文件。
// 怪癖（照 golden 原样，不"修"）：firtool 按 L2Top 的实际用法删掉了一批恒定或没人读的
//   字段——out_a 无 mask/data、out_b 只有 opcode/param/address/data、out_d 无 size、
//   out_e 无 ready。各通道处有注释。
// =============================================================================

