// =============================================================================
// MMIOBridge —— L2 的 TileLink→CHI MMIO 桥（16 个事务槽 + 三个仲裁器 + 胶合逻辑）
//
// Scala：coupledL2/src/main/scala/coupledL2/tl2chi/MMIOBridge.scala，class MMIOBridgeImp。
// 位置：TL2CHICoupledL2 里。核发出的不可缓存访问（MMIO / NC 的 Get、PutFullData、
//   PutPartialData，每笔一个 64 位字）走 TileLink-UL 的 A/D 通道进来，本桥把每笔访问
//   放进一个空闲槽（MMIOBridgeEntry），由槽去走 CHI 的 ReadNoSnp / WriteNoSnpPtl 事务。
//
// 结构（golden 2673 行，绝大部分是 16 个槽 × ~60 根线的逐端口连线）：
//
//     A 通道 ──选第一个空闲槽──▶ entries_0 … entries_15 ──▶ txreqArb（轮转）──▶ CHI TXREQ
//                                         │  │  │        └─▶ mmio_txdat_arb（固定优先）─▶ CHI TXDAT
//                                         │  │  └──────────▶ mmio_channel_D_arb（固定优先）─▶ D 通道
//     CHI RXRSP / RXDAT ──按 txnID 分发到槽号相同的槽──┘  └── io_pCrd_<i>：每槽各自的 P-Credit 查询
//
// 本层手写的只有胶合逻辑（xs_MMIOBridge_core，下面 §1–§4）；槽与仲裁器都是已签核的 child：
//   entries_0..15 = MMIOBridgeEntry / _2 / _4 / _8（同一个 Scala 类，只因 `io.id := i.U` 字面量位宽
//                   随槽号变化被单态化成四个模块：槽 0~1 / 2~3 / 4~7 / 8~15），
//                   核 rtl/uncore/xs_MMIOBridgeEntry_core.sv；
//   txreqArb           = RRArbiterInit_13（rtl/common/RRArbiterInit_13.sv）；
//   mmio_txdat_arb     = Arbiter16_CHIDAT（rtl/uncore/Arbiter16_CHIDAT.sv）；
//   mmio_channel_D_arb = Arbiter16_TLBundleD（rtl/uncore/Arbiter16_TLBundleD.sv）。
// 文件后半部的 golden 同名 wrapper 由 scripts/gen_mmiobridge.py 从 golden 端口表机械生成
// （每个端口必须恰好命中一条接线规则，否则生成失败）；实例名与 golden 一致。
//
// 怪癖（照 golden）：
//   * 选槽是 ParallelPriorityMux(ready_i -> 1<<i)：取编号最小的空闲槽；**一个都不空闲时
//     默认选中槽 15**（优先级 mux 的兜底项），于是 A.valid 会被送进一个 ready=0 的槽——
//     槽自己不收（fire 要 ready），无害，但 entries_15.io_req_valid 与"只有空闲才给"不同。
//   * RXRSP 的 ready 恒 1（Scala 用 assert 保证总有槽收）；RXDAT 的 ready 取"txnID 对上的槽"的 ready。
//     txnID 是 12 位，只有 0..15 有槽，其余值两种 ready/valid 都落空。
//   * 读保序：任何槽还在等 ReadReceipt（waitOnReadReceipt）时，所有槽的 ReadNoSnp 请求
//     都被挡住——valid 送仲裁器前压掉、槽看到的 ready 也压掉（block）。写请求不受影响。
//   * CHI 请求 / 数据里本桥不用的字段全是常量（qos=0xE、opcode=NonCopyBackWrData 等），见 wrapper。
//
// 本文件导航：
//   xs_MMIOBridge_core ………… §1 选槽  §2 读保序  §3 RXRSP/RXDAT 分发  §4 上游 ready（手写，约 100 行）
//   MMIOBridge（wrapper）…… golden 端口表 / 每槽线束 / 16 个槽 / 3 个仲裁器 / 常量字段
//                            （scripts/gen_mmiobridge.py 生成，其余约 1900 行都是逐端口连线）
// =============================================================================

module xs_MMIOBridge_core #(
  parameter int unsigned NUM_SLOTS = 16
) (
  // TileLink A 通道握手
  input  logic                 a_valid,
  output logic                 a_ready,
  // 每槽的请求口
  input  logic [NUM_SLOTS-1:0] slot_reqReady,          // 槽空闲
  output logic [NUM_SLOTS-1:0] slot_reqValid,          // A.valid 送给被选中的槽
  // 读保序（ReadReceipt）
  input  logic [NUM_SLOTS-1:0] slot_waitOnReadReceipt, // 槽发了要回执的读、回执还没到
  // 每槽的 CHI TXREQ 与轮转仲裁器之间
  input  logic [NUM_SLOTS-1:0] slot_txReqValid,
  input  logic [6:0]           slot_txReqOpcode [NUM_SLOTS],
  output logic [NUM_SLOTS-1:0] slot_txReqReady,
  input  logic [NUM_SLOTS-1:0] txReqArb_inReady,
  output logic [NUM_SLOTS-1:0] txReqArb_inValid,
  // CHI RXRSP / RXDAT 按 txnID 分发
  input  logic                 rxRsp_valid,
  input  logic [11:0]          rxRsp_txnID,
  output logic                 rxRsp_ready,
  output logic [NUM_SLOTS-1:0] slot_rxRspValid,
  input  logic                 rxDat_valid,
  input  logic [11:0]          rxDat_txnID,
  output logic                 rxDat_ready,
  output logic [NUM_SLOTS-1:0] slot_rxDatValid,
  input  logic [NUM_SLOTS-1:0] slot_rxDatReady
);

  localparam logic [6:0] CHI_OPC_READNOSNP = 7'h04;   // CHI REQ opcode ReadNoSnp

  // ===========================================================================
  // §1 选槽：A 通道请求交给编号最小的空闲槽；没有空闲槽时兜底选槽 NUM_SLOTS-1
  // ===========================================================================
  logic [NUM_SLOTS-1:0] selectOH;

  always_comb begin
    selectOH = '0;
    selectOH[NUM_SLOTS-1] = 1'b1;              // 兜底：一个都不空闲
    for (int i = NUM_SLOTS - 2; i >= 0; i--) begin
      if (slot_reqReady[i]) begin
        selectOH = '0;
        selectOH[i] = 1'b1;
      end
    end
  end

  assign slot_reqValid = {NUM_SLOTS{a_valid}} & selectOH;
  assign a_ready       = |slot_reqReady;

  // ===========================================================================
  // §2 读保序：有槽在等 ReadReceipt 时，挡住所有槽的 ReadNoSnp
  // ===========================================================================
  logic anyWaitOnReadReceipt;
  logic [NUM_SLOTS-1:0] blockRead;

  assign anyWaitOnReadReceipt = |slot_waitOnReadReceipt;

  always_comb begin
    for (int i = 0; i < NUM_SLOTS; i++) begin
      blockRead[i]        = (slot_txReqOpcode[i] == CHI_OPC_READNOSNP) & anyWaitOnReadReceipt;
      txReqArb_inValid[i] = slot_txReqValid[i] & ~blockRead[i];
      slot_txReqReady[i]  = txReqArb_inReady[i] & ~blockRead[i];
    end
  end

  // ===========================================================================
  // §3 RXRSP / RXDAT 分发：txnID == 槽号的那个槽收
  // ===========================================================================
  logic [NUM_SLOTS-1:0] rspHit;   // rxRsp_txnID == i
  logic [NUM_SLOTS-1:0] datHit;   // rxDat_txnID == i

  always_comb begin
    for (int i = 0; i < NUM_SLOTS; i++) begin
      rspHit[i] = rxRsp_txnID == 12'(i);
      datHit[i] = rxDat_txnID == 12'(i);
    end
  end

  assign slot_rxRspValid = {NUM_SLOTS{rxRsp_valid}} & rspHit;
  assign slot_rxDatValid = {NUM_SLOTS{rxDat_valid}} & datHit;

  // ===========================================================================
  // §4 上游 ready：RXRSP 恒收；RXDAT 看 txnID 对上的槽
  // ===========================================================================
  assign rxRsp_ready = 1'b1;
  assign rxDat_ready = |(slot_rxDatReady & datHit);

endmodule

